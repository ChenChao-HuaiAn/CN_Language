def 推导阶段(队列行们: list, 预验行们: list, 门禁行们: list, 任务们: list) -> dict:
    """三源合并 → {号: {"阶段","阶段时刻","runner"?}}。
    优先级（同号多信号并存时）：预检红 > 预检绿 > 预检中 > 预检排队
    > 组链与门禁中 > 收工排队 > 开发中；✅ 行只查门禁（收口 sha 10 位
    ↔ 门禁 sha 40 位前缀匹配·红>执行中>绿——任何平台红都须显红供红治理）。
    miss 豁免边界（穷举声明·非静默降级）：⬜/⏸ 行无编排信号=号不出现（无徽标
    =合法终态）；✅ 行无门禁记录（验证轮未跑到/超 200 条被裁）=无徽标自然消隐；
    预验「已取消」态（服务端核出源分支已并入 develop·562）=集成已完成，落门禁/
    无徽标；「完成 但绿为空」=上游异态行，显式跳过预验信号落下游（不当绿不当红）。"""
    队列态 = {}
    for 行 in 队列行们:
        分支 = str(行.get("分支", ""))
        if 分支.startswith("任务/") and 行.get("状态") in ("排队", "集成中"):
            队列态[分支[3:]] = 行
    预验态 = {}
    for 行 in 预验行们:
        源 = str(行.get("源分支") or "")
        # 830：源分支兼容两形态——任务/<号>（新客户端源头归一：integrate 传原始任务分支）与
        #   batch/<号>（历史行/批链形态：830 前客户端入池时传的是批分支名）——否则预验信号
        #   全丢（775 实测：预验在池里跑着·看板却显示「组链与门禁中」）。
        m = re.match(r"^(?:任务|batch)/([0-9]+[a-z]?)$", 源)
        if not m:
            continue
        号 = m.group(1)
        旧 = 预验态.get(号)
        if 旧 is None or int(行.get("序号") or 0) > int(旧.get("序号") or 0):
            预验态[号] = 行
    门禁态 = {}
    for t in 任务们:
        if t.get("状态") != "✅" or len(str(t.get("收口sha") or "")) < 7:
            continue
        收口 = str(t["收口sha"])
        命中们 = [g for g in 门禁行们 if str(g.get("sha", "")).startswith(收口)]
        if not 命中们:
            continue
        红 = [g for g in 命中们 if g.get("绿") == 0]
        跑 = [g for g in 命中们 if g.get("绿") is None]
        # 831 僵死判定：「执行中」行（绿=None）以开始上报时刻计龄——超阈值仍无完成上报
        #   =daemon 中断/部署窗口丢失（实录残留：10-07 事故期 17 条+10-15 部署窗口 4 条），
        #   诚实显「验证中断」而非永久「验证中」（内容已被后续 develop 头线性覆盖）。
        跑活, 跑僵 = [], []
        for g in 跑:
            龄 = 行龄小时(g.get("时刻"))
            if 龄 is None or 龄 <= 验证僵死阈值小时:
                跑活.append(g)
            else:
                跑僵.append(g)
        组 = 红 or 跑活 or 跑僵 or 命中们
        门禁态[t["号"]] = {
            "阶段": (阶段_验证红 if 红
                   else 阶段_验证中 if 跑活
                   else 阶段_验证中断 if 跑僵
                   else 阶段_验证绿),
            "阶段时刻": str(组[0].get("时刻") or ""),
            # 842：验证详情代理参数（红徽标点开看失败用例+归因·gate_result 查询键）
            "sha": str(组[0].get("sha") or ""),
            "平台": str(组[0].get("平台") or "")}
    出 = {}
    for t in 任务们:
        号 = t["号"]
        if t.get("状态") == "✅":
            if 号 in 门禁态:
                出[号] = 门禁态[号]
            continue
        预 = 预验态.get(号)
        if 预 is not None:
            状态 = str(预.get("状态") or "")
            sha10 = str(预.get("sha") or "")[:10]   # 预检详情代理查询键（ci/预验-<sha10>）
            if 状态 == "完成" and 预.get("绿") == 0:
                出[号] = {"阶段": 阶段_预检红, "阶段时刻": str(预.get("更新时刻") or ""), "sha": sha10}
                continue
            if 状态 == "完成" and 预.get("绿") == 1:
                出[号] = {"阶段": 阶段_预检绿, "阶段时刻": str(预.get("更新时刻") or ""), "sha": sha10}
                continue
            if 状态 == "执行中":
                出[号] = {"阶段": 阶段_预检中, "阶段时刻": str(预.get("更新时刻") or ""),
                          "runner": str(预.get("认领者") or ""), "sha": sha10}
                continue
            if 状态 == "排队":
                出[号] = {"阶段": 阶段_预检排队, "阶段时刻": str(预.get("更新时刻") or ""), "sha": sha10}
                continue
        队 = 队列态.get(号)
        if 队 is not None:
            出[号] = {"阶段": 阶段_组链门禁 if 队.get("状态") == "集成中" else 阶段_收工排队,
                      "阶段时刻": str(队.get("更新时刻") or "")}
            continue
        if t.get("状态") == "🏃":
            出[号] = {"阶段": 阶段_开发中, "阶段时刻": str(t.get("更新时刻") or "")}
    return 出


_阶段缓存 = {"时刻": 0.0, "图": {}}


def _套队列鉴权头(请求) -> None:
    """1425/P2-A 全站登录墙：队列服务（8300）GET 亦须鉴权——CN_QUEUE_TOKEN 与
    CN_BOARD_TOKEN 同值（systemd 同源配置·430「queue_client.json 同源」先例），
    本进程（cn-board）注入的是 CN_BOARD_TOKEN，任一在即用；皆空=裸请求（降级面）。
    Bearer 写不可重定向头——跨源跳转不转发令牌（安全复审 P2-A）。"""
    t = os.environ.get("CN_QUEUE_TOKEN") or os.environ.get("CN_BOARD_TOKEN", "")
    if t:
        请求.add_unredirected_header("Authorization", "Bearer " + t)


def 阶段图(任务们: list) -> dict:
    """任务们 → {号: {阶段, 阶段时刻, runner?}}（2s 缓存·照队列态图先例）。
    任务们=台账行字典列表（须含 号/状态/收口sha/更新时刻）。
    错误恢复：队列服务不可达=返回空图（无徽标降级·台账四态仍完整可信）。"""
    import urllib.request
    现 = time.time()
    if 现 - _阶段缓存["时刻"] < 2.0:
        return _阶段缓存["图"]
    图 = {}
    try:
        地址 = os.environ.get("CN_QUEUE_STATUS_URL", "http://127.0.0.1:8300/api/state")
        请求 = urllib.request.Request(地址)
        _套队列鉴权头(请求)
        with urllib.request.urlopen(请求, timeout=2) as r:
            态 = json.loads(r.read().decode("utf-8"))
        图 = 推导阶段(态.get("队列", []), 态.get("预验任务", []),
                      态.get("门禁最近", []), 任务们)
    except (OSError, ValueError):
        图 = {}
    _阶段缓存.update(时刻=现, 图=图)
    return 图


def 取预检详情(sha: str):
    """代理 8300 /api/task_result（内网回环·前端免跨端口暴露）——预检红徽标点开
    看失败用例清单。sha=预验任务 sha（非台账收口 sha）。不可达/无记录=None。"""
    import urllib.request
    import urllib.parse
    地址 = os.environ.get("CN_QUEUE_BASE_URL", "http://127.0.0.1:8300").rstrip("/")
    try:
        请求 = urllib.request.Request(
            f"{地址}/api/task_result?sha={urllib.parse.quote(sha)}")
        _套队列鉴权头(请求)
        with urllib.request.urlopen(请求, timeout=5) as r:
            return json.loads(r.read().decode("utf-8"))
    except (OSError, ValueError):
        return None


