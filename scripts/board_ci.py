def 行龄小时(时刻文本) -> float | None:
    """门禁行「时刻」（%m-%d %H:%M:%S·无年份补当前年）距今年小时数；坏串/未来时刻=None
    （调用方按「当活」处理——宁当在跑·不误标中断）。"""
    if not 时刻文本:
        return None
    try:
        t = datetime.strptime(str(时刻文本).strip(), "%m-%d %H:%M:%S").replace(
            year=datetime.now().year)
    except ValueError:
        return None
    差 = (datetime.now() - t).total_seconds() / 3600
    return 差 if 差 >= 0 else None


