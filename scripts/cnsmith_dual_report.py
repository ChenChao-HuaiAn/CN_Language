def 种子区间们(主种子, 轨道数量们):
    """主种子 → 各轨实际种子区间（含端点·只列数量>0 的轨道）。

    偏移口径见 cnsmith_dual_samples.种子派生表（随机 +0/负向 +7/对拍随机 +11/
    矩阵 +3）；实际样本种子 = 起 + i（i=0..数量-1）。"""
    区间们 = []
    for 轨道, 偏移, 随种子 in 种子派生表:
        数量 = int((轨道数量们 or {}).get(轨道, 0) or 0)
        if 数量 <= 0:
            continue
        起 = int(主种子) + 偏移
        区间们.append({"轨道": 轨道, "偏移": 偏移, "起": 起, "止": 起 + 数量 - 1,
                     "数量": 数量, "随种子": 随种子})
    return 区间们


def 区间重叠数(甲, 乙):
    """两闭区间重叠样本数（0=无重叠）。"""
    return max(0, min(甲["止"], 乙["止"]) - max(甲["起"], 乙["起"]) + 1)


def 种子派生信息(主种子, 种子来源, 轨道数量们, 历史种子们=None):
    """种子派生区间 + 重叠警示（主报告/对拍差异报告共用·JSON 可序列化）。

    背景（#1109）：各轨生成种子=主种子+偏移+i，相邻主种子（±1）的区间几乎
    完全重叠（实测主种子 20261018 与 20261019 的 60 样本随机轨道重叠 59/60）。
    来源=命令行 --seed 时报告必须显式警示并引导默认时间戳种子；来源=时间戳
    时提示同秒连跑/循环共用主种子的残余风险。`历史种子们`=[(轮次名, 主种子,
    轨道数量们)]：给归档内其他轮次的实测重叠数（无归档时为空列表）。"""
    区间们 = 种子区间们(主种子, 轨道数量们)
    随种子们 = [x for x in 区间们 if x["随种子"] and x["数量"] > 1]
    时间戳 = "时间戳" in (种子来源 or "")
    if 时间戳:
        警示 = ("时间戳种子（默认·%%y%%m%%d%%H%%M%%S 秒级）——邻近轮次自然错开；"
                "同秒并发/--轮 循环共用主种子时仍会重叠，届时请拉开启动间隔。")
    elif not 随种子们:
        警示 = ("⚠ 手工主种子：本轨未取随机样本（内置/目录/矩阵面与种子无关）；"
                "但相邻主种子在随机/负向/对拍随机轨道仍会大面积重叠"
                "（实测主种子 20261018 与 20261019 随机轨道重叠 59/60）——跨轮请"
                "省略 --seed 使用默认时间戳种子。")
    else:
        重叠文 = "、".join("%s 重叠 %d/%d" % (x["轨道"], x["数量"] - 1, x["数量"])
                          for x in 随种子们) or "无（样本数<=1）"
        最大样本 = max([x["数量"] for x in 随种子们] or [0])
        警示 = ("⚠ 手工主种子：相邻主种子（±1）派生区间大面积重叠（%s；"
                "实测主种子 20261018 与 20261019 随机轨道重叠 59/60）——"
                "邻近轮次请省略 --seed 使用默认时间戳种子，或把主种子步长拉大到 "
                "> %d（最大样本数 %d + 偏移跨度）。"
                % (重叠文, 最大样本 + 12, 最大样本))
    历史 = []
    for 轮次名, 旧主种子, 旧数量们 in (历史种子们 or []):
        旧区间们 = 种子区间们(旧主种子, 旧数量们)
        for 新区间 in 区间们:
            if not 新区间["随种子"]:
                continue            # 确定性内容（矩阵）不算种子重叠
            旧 = next((x for x in 旧区间们 if x["轨道"] == 新区间["轨道"]), None)
            if 旧 is None:
                continue
            重叠 = 区间重叠数(新区间, 旧)
            if 重叠 <= 0:
                continue
            历史.append({
                "轮次": 轮次名, "旧主种子": 旧主种子, "轨道": 新区间["轨道"],
                "重叠": 重叠, "新样本数": 新区间["数量"],
                "旧样本数": 旧["数量"],
                "比例": "%d/%d" % (重叠, min(新区间["数量"], 旧["数量"])),
            })
    return {"主种子": 主种子, "种子来源": 种子来源, "区间们": 区间们,
            "警示": 警示, "历史重叠": 历史}


def 种子报告节(种子信息):
    """种子派生信息 → MD 行（主报告与对拍差异报告共用·单一渲染源）。"""
    if not 种子信息:
        return []
    节 = ["## 种子派生区间提示（#1109）",
         "- 主种子：%s ｜ 来源：%s"
         % (种子信息["主种子"], 种子信息["种子来源"])]
    for x in 种子信息["区间们"]:
        节.append("- %s：主种子%+d → 种子区间 [%d, %d]（%d 个%s）"
                  % (x["轨道"], x["偏移"], x["起"], x["止"], x["数量"],
                     "" if x["随种子"] else "·确定性内容（种子仅注释）"))
    节.append("- %s" % 种子信息["警示"])
    for h in 种子信息["历史重叠"][:8]:
        节.append("- 与轮次 %s（主种子 %s）%s 重叠 %s"
                  % (h["轮次"], h["旧主种子"], h["轨道"], h["比例"]))
    return 节


def 写差异报告(轮目录, 记录, 结果们, 参数):
    """结构化差异报告落盘（JSON + MD）。返回 (json相对, md相对, 候选, 跳过, 一致)。"""
    out = pathlib.Path(轮目录) / "对拍"
    out.mkdir(parents=True, exist_ok=True)
    候选 = [r for r in 结果们 if r.get("判定") not in (判定_一致, 判定_跳过)]
    for r in 候选:                    # 兜底：任何候选路径都必须给建议立案标题（不空列）
        if not r.get("建议立案"):
            r["建议立案"] = 建议立案标题(r)
    跳过 = [r for r in 结果们 if r.get("判定") == 判定_跳过]
    一致 = len(结果们) - len(候选) - len(跳过)
    结构 = {
        "轮次": 记录["轮次"], "时刻": 记录["时刻"], "平台": 记录["平台"],
        "编译器": 记录.get("编译器", {}),
        "参数": 参数,
        "样本数": len(结果们), "一致": 一致, "候选数": len(候选), "跳过数": len(跳过),
        "建议立案": [r["建议立案"] for r in 候选 if r.get("建议立案")],
        "候选": 候选,
        "跳过": [{"样本": r["样本"], "来源": r["来源"], "源码": r["源码"],
                "原因": r.get("原因", ""), "详情": r.get("详情", "")} for r in 跳过],
        "全部结果": 结果们,
    }
    种子信息 = None
    if 参数.get("主种子") is not None:
        种子信息 = 种子派生信息(
            参数["主种子"], 参数.get("种子来源", "?"),
            {"对拍随机": 参数.get("随机", 0), "对拍矩阵": 参数.get("矩阵", 0)},
            参数.get("历史种子们"))
        结构["种子派生"] = 种子信息
    json路径 = out / "差异报告.json"
    json路径.write_text(json.dumps(结构, ensure_ascii=False, indent=1), encoding="utf-8")
    md = ["# 同源码双编译 stdout 对拍报告（%s）" % 记录["轮次"], "",
          "- 平台：%s ｜ 样本 %d（一致 %d·候选 %d·跳过 %d）"
          % (记录["平台"], len(结果们), 一致, len(候选), len(跳过)),
          "- 参数：%s" % json.dumps(参数, ensure_ascii=False),
          "- 判据：双侧编译→运行→rc+stdout 逐行（stderr %s）"
          % ("参与" if 参数.get("比stderr") else "仅记录"),
          "- 跳过/不对齐>0 时轨道状态=**无效**（exe 码 2·无结果不算过）",
          "", "## 建议立案标题（%d 件·不自动写服务端）" % len(候选)]
    if 种子信息:
        md[7:7] = 种子报告节(种子信息)   # 插在「建议立案标题」节之前（头部 7 行之后）
    if not 候选:
        md.append("零候选。")
    for r in 候选:
        md.append("- %s" % (r.get("建议立案") or "(标题生成失败)"))
    md += ["", "## 候选明细", ""]
    if not 候选:
        md.append("零候选。")
    for r in 候选:
        md += ["### %s（%s）" % (r["样本"], r["来源"]),
               "- 判定：**%s** ｜ 原因：`%s` ｜ 源码：`%s`"
               % (r["判定"], r.get("原因", "?"), r["源码"]),
               "- 详情：%s" % r.get("详情", ""),
               "- 宿主：编译rc=%s rc=%s stdout=%d行 stderr=%d行" % (
                   r["宿主"].get("编译rc"), r["宿主"].get("rc"),
                   r["宿主"].get("stdout行数", 0), r["宿主"].get("stderr行数", 0)),
               "- v2：编译=%s rc=%s stdout=%d行 stderr=%d行" % (
                   r["v2"].get("编译"), r["v2"].get("rc"),
                   r["v2"].get("stdout行数", 0), r["v2"].get("stderr行数", 0))]
        首 = r.get("首差异")
        if 首:
            md.append("- " + 首差异文案(首))
        md += ["- 宿主 stdout：", "```", 截断(r["宿主"].get("stdout", ""), 3000), "```",
               "- v2 stdout：", "```", 截断(r["v2"].get("stdout", ""), 3000), "```"]
        if r["宿主"].get("stderr") or r["v2"].get("stderr"):
            md += ["- 宿主 stderr：", "```", 截断(r["宿主"].get("stderr", ""), 2000), "```",
                   "- v2 stderr：", "```", 截断(r["v2"].get("stderr", ""), 2000), "```"]
        if r["宿主"].get("编译输出"):
            md += ["- 宿主编译输出：", "```",
                   截断(r["宿主"].get("编译输出", ""), 2000), "```"]
        if r["v2"].get("编译输出"):
            md += ["- v2 编译输出：", "```",
                   截断(r["v2"].get("编译输出", ""), 2000), "```"]
        md.append("")
    if 跳过:
        md += ["## 跳过（时间预算/配置不对齐·无结果不算过）", ""]
        for r in 跳过:
            md.append("- %s（%s）[%s]：%s" % (
                r["样本"], r["来源"], r.get("原因", ""), r.get("详情", "")))
        md.append("")
    md += ["", "## 全样本判定表", "",
           "| 样本 | 来源 | 宿主 | v2 | 判定 | 原因 |", "|---|---|---|---|---|---|"]
    for r in 结果们:
        宿主文, v2文 = 记录速记(r)
        md.append("| %s | %s | %s | %s | %s | %s |" % (
            r["样本"], r["来源"], 宿主文.replace("|", "/"),
            v2文.replace("|", "/"), r["判定"], r.get("原因", "").replace("|", "/")))
    md.append("")
    md路径 = out / "差异报告.md"
    md路径.write_text("\n".join(md), encoding="utf-8")
    return (str(json路径), str(md路径), 候选, 跳过, 一致)
