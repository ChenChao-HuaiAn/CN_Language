#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""CN-Smith 对拍轨道·报告层（1130 拆分：判定词表/原因闭集/差异报告/建议立案）。

与 cnsmith_dual.py 的分工：
  cnsmith_dual.py   样本准备 + 判定 + 单样本双编译 + 轨道入口 + CLI
  本模块            判定/原因常量 + 截断 + 记录速记 + 建议立案标题 + 差异报告落盘
  cnsmith_dual_selftest.py  自校验（判定层正/反例 + 报告结构 + 可选端到端）

报告契约（P0-1 跳过不当绿）：轨道层在跳过>0 时状态置「无效」（cnsmith_run
汇总判定→exit 2）；本模块报告显式列「跳过（时间预算·无结果不算过）」。
"""
import json
import pathlib

# 判定大类（闭集·报告/机读统一；新增判定须同步词表——闭集外传入即断言显形）
判定_一致 = "一致"
判定_行为分叉 = "行为分叉"
判定_拒绝不一致 = "拒绝不一致"
判定_工具链 = "工具链/产物异常"
判定_宿主基线无效 = "宿主基线无效"
判定_跳过 = "跳过"
判定_抽查异常 = "抽查异常"

# 原因闭集（审查 P2-4：分类按原因可机械审计；判定大类 × 原因细分方向）
原因_一致 = "rc+stdout一致"
原因_RC不一致 = "退出码不一致"
原因_STDOUT不一致 = "stdout不一致"
原因_STDERR不一致 = "stderr不一致"
原因_宿主拒v2放 = "宿主拒v2放"
原因_宿主过v2拒 = "宿主过v2拒"
原因_宿主拒绝负测配置 = "宿主拒绝负测源码"
原因_v2产错误产物 = "v2拒绝后产asm"
原因_汇编失败 = "v2汇编失败"
原因_链接失败 = "v2链接失败"
原因_符号自检失败 = "v2符号自检失败"
原因_v2未产asm = "v2未生成asm"
原因_v2未达运行 = "v2闭环未达运行"
原因_宿主基线 = "宿主基线无效"
原因_宿主崩溃 = "宿主产物崩溃"
原因_配置退出码不符 = "宿主退出码与配置不符"
原因_配置诊断锚不符 = "宿主诊断缺配置锚"
原因_配置不对齐 = "用例配置不对齐"
原因_预算跳过 = "时间预算耗尽"
原因_抽查异常 = "抽查执行异常"

# 单侧输出写入报告的截断上限（字符）——报告须给「两侧输出」，超限显式标注
输出截断上限 = 8000


def 截断(文本, 上限=输出截断上限):
    """截断并显式标注（miss 不静默：截断本身是报告事实，不是丢数据）。"""
    文本 = 文本 or ""
    if len(文本) <= 上限:
        return 文本
    return 文本[:上限] + "\n…（截断：原文 %d 字符，上限 %d）" % (len(文本), 上限)


def 首差异文案(首):
    """首差异 → 一行人读定位（stdout/stderr 才带行号；编译判据/rc 不编造行号）。"""
    if not 首:
        return "无首差异定位"
    甲侧, 乙侧 = 首.get("甲侧", "宿主"), 首.get("乙侧", "v2")
    if 首.get("类别") in ("stdout", "stderr"):
        return "首差异第 %s 行（%s）：%s=%r ｜ %s=%r" % (
            首.get("行"), 首.get("类别"), 甲侧, 首.get("甲"), 乙侧, 首.get("乙"))
    return "首差异（%s）：%s=%r ｜ %s=%r" % (
        首.get("类别"), 甲侧, 首.get("甲"), 乙侧, 首.get("乙"))


def 建议立案标题(记录):
    """分叉候选 → 建议立案标题（人读；不自动写服务端——防误写）。"""
    if 记录.get("判定") in (判定_一致, 判定_跳过):
        return ""
    return "〔1130对拍〕%s[%s]：样本 %s（%s）宿主×v2 —— %s" % (
        记录.get("判定", "?"), 记录.get("原因", "?"), 记录.get("样本", "?"),
        记录.get("来源", "?"), 首差异文案(记录.get("首差异")))


def 记录速记(记录):
    """结果明细表的人读速记（报告/日志共用）。"""
    if 记录.get("判定") == 判定_跳过:
        return "跳过", "跳过"
    宿主 = 记录.get("宿主", {})
    v2 = 记录.get("v2", {})
    宿主文 = ("rc=%s 输出%d行" % (宿主.get("rc"), 宿主.get("stdout行数", 0))
              if 宿主.get("rc") is not None else
              "编译拒 rc=%s" % 宿主.get("编译rc"))
    v2文 = ("rc=%s 输出%d行" % (v2.get("rc"), v2.get("stdout行数", 0))
            if v2.get("rc") is not None else (v2.get("编译") or "?"))
    return 宿主文, v2文


def 写差异报告(轮目录, 记录, 结果们, 参数):
    """结构化差异报告落盘（JSON + MD）。返回 (json相对, md相对, 候选, 跳过, 一致)。"""
    out = pathlib.Path(轮目录) / "对拍"
    out.mkdir(parents=True, exist_ok=True)
    候选 = [r for r in 结果们 if r.get("判定") not in (判定_一致, 判定_跳过)]
    for r in 候选:                    # 兜底：任何候选路径都必须给建议立案标题（不空列）
        if not r.get("建议立案"):
            r["建议立案"] = 建议立案标题(r)
    跳过 = [r for r in 结果们 if r.get("判定") == 判定_跳过]
    一致 = len(结果们) - len(候选) - len(跳过)
    结构 = {
        "轮次": 记录["轮次"], "时刻": 记录["时刻"], "平台": 记录["平台"],
        "编译器": 记录.get("编译器", {}),
        "参数": 参数,
        "样本数": len(结果们), "一致": 一致, "候选数": len(候选), "跳过数": len(跳过),
        "建议立案": [r["建议立案"] for r in 候选 if r.get("建议立案")],
        "候选": 候选,
        "跳过": [{"样本": r["样本"], "来源": r["来源"], "源码": r["源码"],
                "原因": r.get("原因", ""), "详情": r.get("详情", "")} for r in 跳过],
        "全部结果": 结果们,
    }
    json路径 = out / "差异报告.json"
    json路径.write_text(json.dumps(结构, ensure_ascii=False, indent=1), encoding="utf-8")
    md = ["# 同源码双编译 stdout 对拍报告（%s）" % 记录["轮次"], "",
          "- 平台：%s ｜ 样本 %d（一致 %d·候选 %d·跳过 %d）"
          % (记录["平台"], len(结果们), 一致, len(候选), len(跳过)),
          "- 参数：%s" % json.dumps(参数, ensure_ascii=False),
          "- 判据：双侧编译→运行→rc+stdout 逐行（stderr %s）"
          % ("参与" if 参数.get("比stderr") else "仅记录"),
          "- 跳过/不对齐>0 时轨道状态=**无效**（exe 码 2·无结果不算过）",
          "", "## 建议立案标题（%d 件·不自动写服务端）" % len(候选)]
    if not 候选:
        md.append("零候选。")
    for r in 候选:
        md.append("- %s" % (r.get("建议立案") or "(标题生成失败)"))
    md += ["", "## 候选明细", ""]
    if not 候选:
        md.append("零候选。")
    for r in 候选:
        md += ["### %s（%s）" % (r["样本"], r["来源"]),
               "- 判定：**%s** ｜ 原因：`%s` ｜ 源码：`%s`"
               % (r["判定"], r.get("原因", "?"), r["源码"]),
               "- 详情：%s" % r.get("详情", ""),
               "- 宿主：编译rc=%s rc=%s stdout=%d行 stderr=%d行" % (
                   r["宿主"].get("编译rc"), r["宿主"].get("rc"),
                   r["宿主"].get("stdout行数", 0), r["宿主"].get("stderr行数", 0)),
               "- v2：编译=%s rc=%s stdout=%d行 stderr=%d行" % (
                   r["v2"].get("编译"), r["v2"].get("rc"),
                   r["v2"].get("stdout行数", 0), r["v2"].get("stderr行数", 0))]
        首 = r.get("首差异")
        if 首:
            md.append("- " + 首差异文案(首))
        md += ["- 宿主 stdout：", "```", 截断(r["宿主"].get("stdout", ""), 3000), "```",
               "- v2 stdout：", "```", 截断(r["v2"].get("stdout", ""), 3000), "```"]
        if r["宿主"].get("stderr") or r["v2"].get("stderr"):
            md += ["- 宿主 stderr：", "```", 截断(r["宿主"].get("stderr", ""), 2000), "```",
                   "- v2 stderr：", "```", 截断(r["v2"].get("stderr", ""), 2000), "```"]
        if r["宿主"].get("编译输出"):
            md += ["- 宿主编译输出：", "```",
                   截断(r["宿主"].get("编译输出", ""), 2000), "```"]
        if r["v2"].get("编译输出"):
            md += ["- v2 编译输出：", "```",
                   截断(r["v2"].get("编译输出", ""), 2000), "```"]
        md.append("")
    if 跳过:
        md += ["## 跳过（时间预算/配置不对齐·无结果不算过）", ""]
        for r in 跳过:
            md.append("- %s（%s）[%s]：%s" % (
                r["样本"], r["来源"], r.get("原因", ""), r.get("详情", "")))
        md.append("")
    md += ["", "## 全样本判定表", "",
           "| 样本 | 来源 | 宿主 | v2 | 判定 | 原因 |", "|---|---|---|---|---|---|"]
    for r in 结果们:
        宿主文, v2文 = 记录速记(r)
        md.append("| %s | %s | %s | %s | %s | %s |" % (
            r["样本"], r["来源"], 宿主文.replace("|", "/"),
            v2文.replace("|", "/"), r["判定"], r.get("原因", "").replace("|", "/")))
    md.append("")
    md路径 = out / "差异报告.md"
    md路径.write_text("\n".join(md), encoding="utf-8")
    return (str(json路径), str(md路径), 候选, 跳过, 一致)
