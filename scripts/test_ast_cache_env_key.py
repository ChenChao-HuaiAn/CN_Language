# ==================== 缓存条目读取与完整性校验 ====================

条目头长 = 52          # 魔数 8 + 5×u64 + 载荷长 u32
条目魔数 = b"CNASTC01"


def fnv1a64(数据: bytes) -> int:
    值 = 14695981039346656037
    for 字节 in 数据:
        值 ^= 字节
        值 = (值 * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return 值


def 校验条目完整(路径: Path):
    """返回 None=完整；否则返回缺陷说明（头/长度/FNV 三层机械校验）。"""
    数据 = 路径.read_bytes()
    if len(数据) < 条目头长:
        return "文件长度 %d < 头部 %d" % (len(数据), 条目头长)
    if 数据[:8] != 条目魔数:
        return "魔数不符: %r" % 数据[:8]
    载荷长 = int.from_bytes(数据[48:52], "little")
    if 载荷长 != len(数据) - 条目头长:
        return "载荷长度不符（头=%d 实际=%d）" % (载荷长, len(数据) - 条目头长)
    存储校验和 = int.from_bytes(数据[40:48], "little")
    实际校验和 = fnv1a64(数据[条目头长:])
    if 存储校验和 != 实际校验和:
        return "FNV 校验和不符（头=%016x 实际=%016x）" % (存储校验和, 实际校验和)
    return None


def 条目快照(缓存目录: Path):
    return {p.name: p.read_bytes() for p in sorted(缓存目录.glob("*.cnast"))}


统计模式 = re.compile(
    r"\[AST 缓存\] 命中=(\d+) 首建=(\d+) 失效重建=(\d+) 损坏回退=(\d+) "
    r"写入=(\d+) 写失败=(\d+) 序列化失败=(\d+)")


class 编译结果:
    def __init__(self, 返回码, 标准输出, 标准错误, 统计, 诊断文本):
        self.返回码 = 返回码
        self.标准输出 = 标准输出
        self.标准错误 = 标准错误
        self.统计 = 统计
        self.诊断文本 = 诊断文本


def 旁路环境(缓存目录: Path, 额外=None):
    环境 = dict(os.environ)
    for 键 in ("CN_AST_CACHE_VERIFY", "CN_NO_AST_CACHE", "CN_PROGRAM_CACHE_VERIFY",
               "CN_NO_PROGRAM_CACHE", "CN_PROGRAM_CACHE_DIR"):
        环境.pop(键, None)
    环境["CN_AST_CACHE_DIR"] = str(缓存目录)
    环境["CN_AST_CACHE_STATS"] = "1"
    环境["CN_NO_PROGRAM_CACHE"] = "1"  # 程序缓存会绕过 AST 解析：本测试只看 AST 缓存
    if 额外:
        环境.update(额外)
    return 环境


def 编译(编译器: Path, 工作目录: Path, 源文件: Path, 输出: Path,
         宏列表, 缓存目录: Path, 额外环境=None) -> 编译结果:
    命令 = [str(编译器), "compile", str(源文件), "--target", 本机目标平台(),
            "--output", str(输出)]
    for 宏 in 宏列表:
        命令 += ["-D", 宏]
    结果 = subprocess.run(命令, cwd=str(工作目录), capture_output=True, timeout=180,
                          env=旁路环境(缓存目录, 额外环境))
    输出文本 = (结果.stdout + 结果.stderr).decode("utf-8", errors="replace")
    匹配 = 统计模式.findall(输出文本)
    断言(bool(匹配), "编译输出含 [AST 缓存] 统计行（CN_AST_CACHE_STATS=1 生效）")
    字段 = ("命中", "首建", "失效重建", "损坏回退", "写入", "写失败", "序列化失败")
    统计 = dict(zip(字段, (int(v) for v in 匹配[-1])))
    诊断文本 = "\n".join(
        行 for 行 in 输出文本.splitlines()
        if "[AST 缓存]" not in 行 and not 行.startswith("编译成功"))
    assert 结果.returncode == 0, "编译失败（rc=%d）：%s" % (结果.returncode, 输出文本[-800:])
    return 编译结果(结果.returncode, 结果.stdout, 结果.stderr, 统计, 诊断文本)


