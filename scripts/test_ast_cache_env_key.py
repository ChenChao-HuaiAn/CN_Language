def 场景1_交替宏(编译器, 工作目录, 源文件, 缓存目录):
    print("[场景①] 交替宏：条目分离 + 跨进程命中 + 产物一致")
    甲1 = 编译(编译器, 工作目录, 源文件, 工作目录 / "甲1.asm", ["甲"], 缓存目录)
    断言(甲1.统计["首建"] == 1 and 甲1.统计["命中"] == 0, "甲 首次=首建 1（无旧条目）")
    快照 = 条目快照(缓存目录)
    断言(len(快照) == 1, "甲 首次后缓存条目数=1（实际 %d）" % len(快照))
    甲条目名 = next(iter(快照))
    断言(校验条目完整(缓存目录 / 甲条目名) is None, "甲 条目头/长度/FNV 完整")

    乙1 = 编译(编译器, 工作目录, 源文件, 工作目录 / "乙1.asm", ["乙"], 缓存目录)
    断言(乙1.统计["首建"] == 1 and 乙1.统计["命中"] == 0, "乙 首次=首建 1（独立环境条目）")
    快照2 = 条目快照(缓存目录)
    断言(len(快照2) == 2, "甲/乙 两个宏集合产生两个条目（实际 %d）" % len(快照2))
    断言(甲条目名 in 快照2 and 快照2[甲条目名] == 快照[甲条目名],
         "乙 编译未覆盖甲条目（条目身份含环境摘要）")
    断言(校验条目完整(缓存目录 / next(n for n in 快照2 if n != 甲条目名)) is None,
         "乙 条目头/长度/FNV 完整")

    甲2 = 编译(编译器, 工作目录, 源文件, 工作目录 / "甲2.asm", ["甲"], 缓存目录)
    断言(甲2.统计["命中"] == 1 and 甲2.统计["首建"] == 0
         and 甲2.统计["失效重建"] == 0 and 甲2.统计["写入"] == 0,
         "甲 第三次命中（跨进程环境摘要稳定·无失效重建/写入）")
    乙2 = 编译(编译器, 工作目录, 源文件, 工作目录 / "乙2.asm", ["乙"], 缓存目录)
    断言(乙2.统计["命中"] == 1 and 乙2.统计["写入"] == 0, "乙 第四次命中（各自稳定命中）")
    断言(len(条目快照(缓存目录)) == 2, "交替四次后条目数仍=2（互不覆盖）")

    甲1汇编 = (工作目录 / "甲1.asm").read_bytes()
    乙1汇编 = (工作目录 / "乙1.asm").read_bytes()
    断言(甲1汇编 == (工作目录 / "甲2.asm").read_bytes(), "甲 第三次命中产物与首次逐字节一致")
    断言(乙1汇编 == (工作目录 / "乙2.asm").read_bytes(), "乙 第四次命中产物与首次逐字节一致")
    断言(甲1汇编 != 乙1汇编, "两个宏集合产物确不同（测试源条件编译生效）")

    无缓存 = 编译(编译器, 工作目录, 源文件, 工作目录 / "甲_无缓存.asm", ["甲"], 缓存目录,
                 {"CN_NO_AST_CACHE": "1"})
    断言(无缓存.统计["命中"] == 0 and 无缓存.统计["首建"] == 0,
         "无缓存对照未走缓存（CN_NO_AST_CACHE=1）")
    断言(甲1汇编 == (工作目录 / "甲_无缓存.asm").read_bytes(),
         "有缓存汇编与无缓存完整解析逐字节一致")
    断言(甲1.诊断文本 == 甲2.诊断文本,
         "命中时诊断/警告行为不变（首次与命中诊断文本一致）")
    return 甲条目名


def 场景2_损坏显形(编译器, 工作目录, 源文件, 缓存目录, 甲条目名):
    print("[场景②] 损坏条目显形 + 回退完整解析")
    基准 = (工作目录 / "甲1.asm").read_bytes()
    甲条目 = 缓存目录 / 甲条目名
    assert 甲条目.exists(), "场景② 未找到甲条目: %s" % 甲条目
    # ① 截断（长度不足头部）
    甲条目.write_bytes(甲条目.read_bytes()[:20])
    截断 = 编译(编译器, 工作目录, 源文件, 工作目录 / "损坏1.asm", ["甲"], 缓存目录)
    断言("缓存条目无效" in 截断.标准错误.decode("utf-8", errors="replace"),
         "截断条目命中显形警告（[AST 缓存] 缓存条目无效）")
    断言(截断.统计["损坏回退"] == 1 and 截断.统计["写入"] == 1,
         "截断条目计数=损坏回退 1 + 重建写入 1")
    断言((工作目录 / "损坏1.asm").read_bytes() == 基准, "截断回退产物与基准一致")
    断言(校验条目完整(甲条目) is None, "截断条目已被重建为完整条目")

    # ② 翻转载荷末字节（校验和/反序列化失败）
    数据 = bytearray(甲条目.read_bytes())
    数据[-1] ^= 0xFF
    甲条目.write_bytes(bytes(数据))
    翻转 = 编译(编译器, 工作目录, 源文件, 工作目录 / "损坏2.asm", ["甲"], 缓存目录)
    断言("缓存条目无效" in 翻转.标准错误.decode("utf-8", errors="replace"),
         "校验和损坏命中显形警告")
    断言(翻转.统计["损坏回退"] >= 1 and 翻转.统计["写入"] == 1,
         "校验和损坏计数=损坏回退 + 重建写入")
    断言((工作目录 / "损坏2.asm").read_bytes() == 基准, "校验和损坏回退产物与基准一致")

    # ③ 格式版本不符（同步重算 FNV 校验和：故障面只留载荷内版本字段，
    #   验证「版本不符」经反序列化检查显形，而不是被校验和提前兜住）
    数据 = bytearray(甲条目.read_bytes())
    数据[条目头长:条目头长 + 4] = (0xFFFFFFFF).to_bytes(4, "little")
    数据[40:48] = fnv1a64(bytes(数据[条目头长:])).to_bytes(8, "little")
    甲条目.write_bytes(bytes(数据))
    断言(校验条目完整(甲条目) is None, "版本篡改后头/长度/FNV 仍完整（故障面只留版本）")
    版本 = 编译(编译器, 工作目录, 源文件, 工作目录 / "损坏3.asm", ["甲"], 缓存目录)
    版本错误 = 版本.标准错误.decode("utf-8", errors="replace")
    断言("缓存条目无效" in 版本错误 and "缓存格式版本不符" in 版本错误,
         "格式版本不符命中显形警告（版本字段被反序列化检查捕获）")
    断言(版本.统计["损坏回退"] == 1 and 版本.统计["写入"] == 1,
         "版本不符计数=损坏回退 1 + 重建写入 1")
    断言((工作目录 / "损坏3.asm").read_bytes() == 基准, "版本不符回退产物与基准一致")

    恢复 = 编译(编译器, 工作目录, 源文件, 工作目录 / "恢复.asm", ["甲"], 缓存目录)
    断言(恢复.统计["命中"] == 1 and 恢复.统计["损坏回退"] == 0, "重建后再次编译恢复命中")


def 场景3_并发写(编译器, 工作目录, 源文件, 缓存目录):
    print("[场景③] 多进程并发写同一缓存条目：无半文件/无 tmp 残留（3 轮压测）")
    # 并发写竞争窗口=解析耗时：用大源（2500 个填充函数·实测单编译 ~1.6s）
    # 让多个进程同时处于「未命中→解析→写」阶段，制造真实多写者竞争。
    基准 = 编译(编译器, 工作目录, 源文件, 工作目录 / "并发基准.asm", ["乙"], 缓存目录,
               {"CN_NO_AST_CACHE": "1"})
    断言(基准.统计["命中"] == 0 and 基准.统计["首建"] == 0, "并发基准=无缓存完整解析")
    基准汇编 = (工作目录 / "并发基准.asm").read_bytes()
    # 1213：单轮只覆盖「无旧条目并发首建」；多轮覆盖「条目已存在时并发陈旧重建/
    #   覆盖写」——每轮清空条目让 8 进程再次同时未命中，重复暴露 tmp 竞争窗口。
    #   启动闸门：子进程先等 go 文件出现再 exec 编译器，消除 OS 调度/杀毒扫描导致
    #   后启动者在先完成者写条目后才开始的退化（实测全量构建刚结束的负载窗口下
    #   第 2 轮首建塌缩到 1/8=竞争未发生的假红，非缓存缺陷）。
    并发启动器 = (
        "import os,sys,subprocess,time\n"
        "go=sys.argv[1]\n"
        "while not os.path.exists(go): time.sleep(0.002)\n"
        "sys.exit(subprocess.call(sys.argv[2:]))\n")
    轮数 = 3
    for 轮 in range(1, 轮数 + 1):
        for 条目 in 缓存目录.glob("*.cnast"):
            条目.unlink()
        闸门 = 工作目录 / ("go_%d" % 轮)
        闸门.unlink(missing_ok=True)
        进程们 = []
        for 序 in range(8):
            输出 = 工作目录 / ("并发%d_%d.asm" % (轮, 序))
            命令 = [sys.executable, "-c", 并发启动器, str(闸门), str(编译器),
                    "compile", str(源文件), "--target", 本机目标平台(),
                    "--output", str(输出), "-D", "乙"]
            进程们.append((序, 输出, subprocess.Popen(
                命令, cwd=str(工作目录), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                env=旁路环境(缓存目录))))
        闸门.write_text("go", encoding="utf-8")  # 放行：8 进程毫秒级同时开跑
        日志 = []
        for 序, 输出, 进程 in 进程们:
            标准输出, 标准错误 = 进程.communicate(timeout=300)
            输出文本 = (标准输出 + 标准错误).decode("utf-8", errors="replace")
            日志.append(输出文本)
            断言(进程.returncode == 0, "第 %d 轮并发进程 %d rc=0（%s）"
                 % (轮, 序, (标准输出 + 标准错误).decode("utf-8", errors="replace")[-300:]))
            断言(输出.read_bytes() == 基准汇编,
                 "第 %d 轮并发进程 %d 产物与基准逐字节一致" % (轮, 序))
        写者数 = sum(1 for 文本 in 日志 if 统计模式.findall(文本)
                    and int(统计模式.findall(文本)[-1][4]) > 0)
        首建数 = sum(1 for 文本 in 日志 if 统计模式.findall(文本)
                    and int(统计模式.findall(文本)[-1][1]) > 0)
        断言(写者数 >= 1, "第 %d 轮：并发进程实际写入条目（写者数 %d/8）" % (轮, 写者数))
        断言(首建数 >= 2, "第 %d 轮：多进程同时未命中后并发写同一条目（首建者 %d/8）"
             % (轮, 首建数))
        条目们 = sorted(缓存目录.glob("*.cnast"))
        断言(len(条目们) == 1, "第 %d 轮：8 进程并发后仅 1 个条目（实际 %d）"
             % (轮, len(条目们)))
        缺陷 = 校验条目完整(条目们[0])
        断言(缺陷 is None, "第 %d 轮：并发条目头/长度/FNV 完整（无半文件）：%s"
             % (轮, 缺陷 or "完整"))
        残留 = list(缓存目录.glob("*.tmp*"))
        断言(not 残留, "第 %d 轮：无 .tmp 临时文件残留（tmp+rename 原子写收尾）" % 轮)
        命中 = 编译(编译器, 工作目录, 源文件, 工作目录 / ("并发后命中%d.asm" % 轮),
                   ["乙"], 缓存目录)
        断言(命中.统计["命中"] == 1 and 命中.统计["损坏回退"] == 0,
             "第 %d 轮：并发写后条目可命中（完整性经真实命中二次确认）" % 轮)
        断言((工作目录 / ("并发后命中%d.asm" % 轮)).read_bytes() == 基准汇编,
             "第 %d 轮：并发命中产物与无缓存基准逐字节一致" % 轮)


def 场景4_编译器身份(编译器, 工作目录, 源文件, 缓存目录):
    print("[场景④] 编译器身份变化：旧 AST 条目不命中、新旧身份各自稳定")
    # 身份 = 可执行文件内容哈希：复制后尾部追加字节（PE/ELF 均容忍尾部附加数据），
    # 内容变→身份变，验证「改解析行为但没递增格式版本」不会误命中旧 AST。
    副本 = 工作目录 / ("cn_identity_copy" + (".exe" if sys.platform.startswith("win") else ""))
    shutil.copyfile(编译器, 副本)
    with open(副本, "ab") as 文件:
        文件.write(b"CN1271-IDENTITY-PROBE")
    原1 = 编译(编译器, 工作目录, 源文件, 工作目录 / "身份_原1.asm", ["甲"], 缓存目录)
    断言(原1.统计["首建"] == 1, "原编译器首次=首建 1")
    原1汇编 = (工作目录 / "身份_原1.asm").read_bytes()
    副本1 = 编译(副本, 工作目录, 源文件, 工作目录 / "身份_副本1.asm", ["甲"], 缓存目录)
    断言(副本1.统计["首建"] == 1 and 副本1.统计["命中"] == 0,
         "身份变化后同源同宏=首建（旧 AST 条目绝不被命中）")
    断言((工作目录 / "身份_副本1.asm").read_bytes() == 原1汇编, "新身份产物与原身份逐字节一致")
    条目们 = sorted(缓存目录.glob("*.cnast"))
    断言(len(条目们) == 2, "两个编译器身份=两个条目（实际 %d）" % len(条目们))
    断言(len({p.name.split("-")[0] for p in 条目们}) == 1,
         "两条目路径哈希相同、环境哈希不同（身份已入文件名身份）")
    副本2 = 编译(副本, 工作目录, 源文件, 工作目录 / "身份_副本2.asm", ["甲"], 缓存目录)
    断言(副本2.统计["命中"] == 1 and 副本2.统计["写入"] == 0, "新身份再次编译稳定命中")
    原2 = 编译(编译器, 工作目录, 源文件, 工作目录 / "身份_原2.asm", ["甲"], 缓存目录)
    断言(原2.统计["命中"] == 1 and 原2.统计["损坏回退"] == 0,
         "原身份条目不受新身份影响（仍命中）")
    断言((工作目录 / "身份_原2.asm").read_bytes() == 原1汇编, "原身份命中产物逐字节一致")


def 场景5_键编码歧义(编译器, 工作目录, 源文件, 缓存目录):
    print("[场景⑤] 环境键字段编码：0x1F 分隔歧义已消除")
    含分隔符宏 = "a\x1fb"          # 单个宏名内嵌 0x1F
    分开宏 = ["a", "b"]            # 两个宏（旧 0x1F 拼接会与上一形态同键）
    单1 = 编译(编译器, 工作目录, 源文件, 工作目录 / "编码_单1.asm", [含分隔符宏], 缓存目录)
    两1 = 编译(编译器, 工作目录, 源文件, 工作目录 / "编码_两1.asm", 分开宏, 缓存目录)
    断言(单1.统计["首建"] == 1 and 两1.统计["首建"] == 1,
         "单宏含 0x1F 与两宏=首建（不同键·不再同串）")
    条目们 = sorted(缓存目录.glob("*.cnast"))
    断言(len(条目们) == 2 and 条目们[0].name != 条目们[1].name,
         "两形态产生两个不同条目（实际 %d）" % len(条目们))
    单2 = 编译(编译器, 工作目录, 源文件, 工作目录 / "编码_单2.asm", [含分隔符宏], 缓存目录)
    两2 = 编译(编译器, 工作目录, 源文件, 工作目录 / "编码_两2.asm", 分开宏, 缓存目录)
    断言(单2.统计["命中"] == 1 and 两2.统计["命中"] == 1, "两形态各自稳定命中")
    断言((工作目录 / "编码_单2.asm").read_bytes() == (工作目录 / "编码_单1.asm").read_bytes()
         and (工作目录 / "编码_两2.asm").read_bytes() == (工作目录 / "编码_两1.asm").read_bytes(),
         "命中产物与首次逐字节一致（两形态产物相同·宏未参与源条件编译）")


def 主程序() -> int:
    解析器 = argparse.ArgumentParser(description="AST 缓存环境键（1271）自测")
    解析器.add_argument("--cn", help="cn 编译器路径（默认自动探测 target/cn[.exe]）")
    解析器.add_argument("--keep", action="store_true", help="保留临时目录取证")
    参数 = 解析器.parse_args()

    编译器 = 查找编译器(参数.cn)
    临时根 = Path(tempfile.mkdtemp(prefix="astcache1271_", dir=str(仓库根 / "target")))
    工作目录 = 临时根 / "work"
    工作目录.mkdir(parents=True)
    print("编译器: %s" % 编译器)
    print("临时根: %s" % 临时根)
    源文件 = 工作目录 / "主.cn"
    源文件.write_text(
        "// 1271 自测：两个宏集合走不同条件编译分支（汇编产物可判别）。\n"
        "函数 主() -> 整32 {\n"
        "    #如果定义 甲\n"
        "    打印(\"甲分支\");\n"
        "    #否则\n"
        "    打印(\"乙分支\");\n"
        "    #结束如果\n"
        "    返回 0;\n"
        "}\n", encoding="utf-8")
    # 并发写场景专用大源：2500 个填充函数把「未命中→解析→写」窗口拉长（实测单编译 ~1.6s），
    # 8 进程同时启动即可形成真实多写者竞争（小源先到者早已写完，命名含进程瞬时
    # 差异源——窗口须明显大于进程启动耗时，2500 规模实测稳定 8/8 同时首建）。
    并发源 = 工作目录 / "并发主.cn"
    行们 = [
        "// 1271 自测并发写：填充函数放大解析窗口。",
        "函数 主() -> 整32 {",
        "    #如果定义 乙",
        "    打印(\"乙分支\");",
        "    #否则",
        "    打印(\"甲分支\");",
        "    #结束如果",
        "    返回 0;",
        "}",
    ]
    for 序 in range(2500):
        行们.append("函数 填充%d() -> 整32 { 返回 %d; }" % (序, 序 % 97))
    并发源.write_text("\n".join(行们) + "\n", encoding="utf-8")
    try:
        甲条目名 = 场景1_交替宏(编译器, 工作目录, 源文件, 临时根 / "cache12")
        场景2_损坏显形(编译器, 工作目录, 源文件, 临时根 / "cache12", 甲条目名)
        场景3_并发写(编译器, 工作目录, 并发源, 临时根 / "cache3")
        场景4_编译器身份(编译器, 工作目录, 源文件, 临时根 / "cache4")
        场景5_键编码歧义(编译器, 工作目录, 源文件, 临时根 / "cache5")
        print("\n全绿：%d 项断言通过" % 通过)
        return 0
    finally:
        if 参数.keep:
            print("保留临时目录: %s" % 临时根)
        else:
            shutil.rmtree(临时根, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(主程序())
