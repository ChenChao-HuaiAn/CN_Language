# ==================== 守卫检测（级别升降启发式） ====================

def 是排除式守卫(ts: list[str], k: int, 后一行: list[str]) -> bool:
    """k 处为 `x < 0`/`x >= 0` 等判定：其后紧跟 `) { 返回`（可跨一行）=排除式。

    排除式语义翻转：`如果 (x >= 0) { 返回 …; }` 之后执行面 x < 0（519 同构取负面），
    反之 `如果 (x < 0) { 返回; }` 之后执行面 x ≥ 0（0-x 安全面）。
    """
    尾 = ts[k + 3:] + 后一行
    for tk in 尾[:4]:
        if tk == "返回":
            return True
        if tk not in (")", "{"):
            return False
    return False


def 检测守卫(代码行们: list[str], 行索引: int, 变量: str) -> tuple[str, int]:
    """同函数窗口内找 变量 的 0 界判定，返回生效执行域（"负值"/"非负", 行号）。

    语义=命中行所在执行面上的变量符号域：包含式守卫（`x < 0 { … }` / `x >= 0 { … }`）
    取守卫域；排除式守卫（守卫块首=`返回`）取补域。负值域（可能达 MIN 面）优先返回。
    """
    起 = max(0, 行索引 - 守卫前窗)
    止 = min(len(代码行们), 行索引 + 守卫后窗 + 1)
    负值 = ("", 0)
    非负 = ("", 0)
    for j in range(起, 止):
        ts = 词法行(代码行们[j])
        后一行 = 词法行(代码行们[j + 1]) if j + 1 < len(代码行们) else []
        for k in range(len(ts) - 2):
            if ts[k] != 变量 or ts[k + 2] != "0":
                continue
            符 = ts[k + 1]
            if 符 not in ("<", "<=", ">", ">="):
                continue
            排除 = 是排除式守卫(ts, k, 后一行)
            负域 = (符 in ("<", "<=")) != 排除        # 异或：排除式翻转执行域
            if 负域 and not 负值[0]:
                负值 = ("负值", j + 1)
            elif not 负域 and not 非负[0]:
                非负 = ("非负", j + 1)
    return 负值 if 负值[0] else 非负


# ==================== 单行规则扫描 ====================

def 操作数描述(ts: list[str], i: int) -> tuple[str, str]:
    """取 `0 -` / `-` 之后的操作数：返回（纯变量名或空, 展示文本）。

    纯标识符=可做守卫检测的变量；成员访问/调用/括号表达式=仅展示（变量空）。
    """
    if i + 2 >= len(ts):
        return "", "?"
    t = ts[i + 2]
    if re.match(标识符模式 + r"$", t):
        展示 = t
        j = i + 3
        while j + 1 < len(ts) and ts[j] == "." and re.match(标识符模式 + r"$", ts[j + 1]):
            展示 += "." + ts[j + 1]
            j += 2
        if j < len(ts) and ts[j] == "(":
            展示 += "(…)"
            return "", 展示
        if 展示 != t:
            return "", 展示
        return t, 展示
    if t == "(":
        return "", "(括号表达式)"
    return "", t


def 扫取负面(ts: list[str], 文件: str, 行号: int, 片段: str,
            代码行们: list[str], 行索引: int) -> list[命中]:
    """R1（`0 - x` 取负族）+ R2（一元负/负号常量族）扫描。"""
    命中们: list[命中] = []
    for i, t in enumerate(ts):
        前 = ts[i - 1] if i > 0 else None
        后 = ts[i + 1] if i + 1 < len(ts) else None
        # --- R1 `0 - x` 族 ---
        if t == "0" and 后 == "-":
            再后 = ts[i + 2] if i + 2 < len(ts) else None
            if 再后 is None:
                pass
            elif re.match(数字模式 + r"$", 再后):
                数值 = re.match(r"\d+", 再后)
                值 = int(数值.group()) if 数值 else 0
                if 值 < 大常量阈值:
                    命中们.append(命中(文件, 行号, "R1b", "常量取负哨兵", "低", 片段,
                                      "编译期常量折叠面（域内安全）"))
                else:
                    两步 = (再后 == MAX64 and ts[i + 3:i + 5] == ["-", "1"])
                    模式 = "MIN 两步构造（安全惯习）" if 两步 else "大常量取负"
                    命中们.append(命中(文件, 行号, "R1c", 模式, "低", 片段,
                                      "常量面·grep 数域内" if not 两步 else "0-MAX-1=MIN·两步防中间溢出"))
            else:
                变量, 展示 = 操作数描述(ts, i)
                守卫 = 检测守卫(代码行们, 行索引, 变量) if 变量 else ("", 0)
                if 守卫[0] == "负值":
                    级别, 注 = "高", f"操作数={展示}；守卫=负值(行 {守卫[1]} · 519 同构「先判负再取负」)"
                elif 守卫[0] == "非负":
                    级别, 注 = "低", f"操作数={展示}；守卫=非负(行 {守卫[1]}·0-非负数必安全)"
                else:
                    级别, 注 = "中", f"操作数={展示}；无同函数守卫 → 需值域归因（能否为 MIN）"
                命中们.append(命中(文件, 行号, "R1a", "取负形态（0 - x）", 级别, 片段, 注))
