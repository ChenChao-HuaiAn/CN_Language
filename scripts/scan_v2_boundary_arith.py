提及模式 = re.compile(r"-\s*9223372036854775808")


def 扫文本(文本: str, 文件: str):
    """扫描单文件文本。返回（命中们, 哨兵数）。"""
    代码行们, 字符串们, 注释们 = 剥离非代码(文本)
    原行们 = 文本.split("\n")
    命中们: list[命中] = []
    哨兵数 = 0
    for 索引, 代码行 in enumerate(代码行们):
        if not 代码行.strip():
            continue
        ts = 词法行(代码行)
        这一行 = 扫一行(ts, 原行们[索引] if 索引 < len(原行们) else 代码行,
                        文件, 索引 + 1, 代码行们, 索引)
        for h in 这一行:
            if h.规则 == "R1b":
                哨兵数 += 1
            # 豁免（同行或前一行）
            前行 = 原行们[索引 - 1] if 索引 > 0 else ""
            豁免, 理由, 告警 = 查豁免(原行们[索引] if 索引 < len(原行们) else "", 前行)
            if 豁免:
                h.豁免理由 = 理由
            elif 告警:
                h.豁免告警 = True
            命中们.append(h)
    # 信息级：字符串/注释中提及 -9223372036854775808（若该行代码区已报 R2c 则不重复）
    已报行 = {h.行号 for h in 命中们 if h.规则 == "R2c"}
    for 行号, 内容 in 字符串们:
        if 提及模式.search(内容) and 行号 not in 已报行:
            命中们.append(命中(文件, 行号, "R7", "位模式字面量·字符串正文", "信息",
                              (原行们[行号 - 1].strip()[:120] if 行号 - 1 < len(原行们) else 内容[:120]),
                              "非代码面·备查"))
    for 行号, 内容 in 注释们:
        if 提及模式.search(内容) and 行号 not in 已报行:
            命中们.append(命中(文件, 行号, "R7", "位模式字面量·注释提及", "信息",
                              (原行们[行号 - 1].strip()[:120] if 行号 - 1 < len(原行们) else 内容[:120]),
                              "非代码面·备查"))
    return 命中们, 哨兵数


def 扫目录(v2根: Path) -> tuple[list[命中], int, list[str]]:
    """扫描 v2 树全部 .cn。返回（命中们, 哨兵总数, 文件相对路径表）。"""
    全部: list[命中] = []
    哨兵总 = 0
    文件们 = sorted(v2根.rglob("*.cn"))
    for f in 文件们:
        相对 = f.relative_to(v2根.parent).as_posix()
        命中们, 哨兵数 = 扫文本(f.read_text(encoding="utf-8"), 相对)
        哨兵总 += 哨兵数
        全部.extend(命中们)
    全部.sort(key=lambda h: (级别序.get(h.级别, 9), h.文件, h.行号, h.规则))
    return 全部, 哨兵总, [f.relative_to(v2根.parent).as_posix() for f in 文件们]


