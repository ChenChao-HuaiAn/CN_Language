# ==================== 剥离与词法 ====================

def 收注(注缓冲: list[str], 注释们: list[tuple[int, str]], 行号: int) -> None:
    """注释缓冲收口（非空才记录·行号=收口位置行）。"""
    注文 = "".join(注缓冲).strip()
    if 注文:
        注释们.append((行号, 注文))
    注缓冲.clear()


def 剥注释(文本: str) -> tuple[str, list[tuple[int, str]]]:
    """第一遍：剥离 // 与嵌套 /* */ 注释（串/字符字面量边界感知·串内 // 不误剥）。

    注释内容替换为空格（换行保留），字符串原文保留给第二遍。返回（文本, 注释们）。
    """
    出: list[str] = []
    注释们: list[tuple[int, str]] = []
    注缓冲: list[str] = []
    行号 = 1
    在块 = 0          # 块注释嵌套深度
    在行注 = False
    在串 = False
    在字符 = False
    i, n = 0, len(文本)
    while i < n:
        c = 文本[i]
        nxt = 文本[i + 1] if i + 1 < n else ""
        if c == "\n":
            出.append(c)
            if 在行注:
                收注(注缓冲, 注释们, 行号)
                在行注 = False
            行号 += 1
            i += 1
            continue
        if 在行注:
            注缓冲.append(c)
            i += 1
            continue
        if 在块:
            if c == "/" and nxt == "*":
                在块 += 1
                i += 2
                continue
            if c == "*" and nxt == "/":
                在块 -= 1
                i += 2
                if 在块 == 0:
                    收注(注缓冲, 注释们, 行号)
                continue
            注缓冲.append(c)
            出.append(" ")
            i += 1
            continue
        if 在串 or 在字符:
            引 = '"' if 在串 else "'"
            出.append(c)
            if c == "\\" and nxt:
                出.append(nxt)
                i += 2
                continue
            if c == 引:
                在串 = False
                在字符 = False
            i += 1
            continue
        if c == "/" and nxt == "/":
            在行注 = True
            i += 2
            continue
        if c == "/" and nxt == "*":
            在块 = 1
            i += 2
            continue
        if c == '"':
            在串 = True
            出.append(c)
            i += 1
            continue
        if c == "'":
            在字符 = True
            出.append(c)
            i += 1
            continue
        出.append(c)
        i += 1
    if 在行注:
        收注(注缓冲, 注释们, 行号)
    return "".join(出), 注释们


def 剥字符串(文本: str) -> tuple[list[str], list[tuple[int, str]]]:
    """第二遍：剥离字符串字面量（此时无注释干扰），收集字符串正文。

    字符串内容替换为空格；返回（代码行们, 字符串们）·行号与原文对齐。
    """
    代码行们: list[str] = []
    字符串们: list[tuple[int, str]] = []
    缓冲: list[str] = []
    串缓冲: list[str] = []
    行号 = 1
    在串 = False
    串起始行 = 0
    i, n = 0, len(文本)
    while i < n:
        c = 文本[i]
        nxt = 文本[i + 1] if i + 1 < n else ""
        if c == "\n":
            if 在串:                     # 未闭合字符串（不应发生·按行容错）
                字符串们.append((串起始行, "".join(串缓冲)))
                串缓冲.clear()
                在串 = False
            代码行们.append("".join(缓冲))
            缓冲.clear()
            行号 += 1
            i += 1
            continue
        if 在串:
            if c == "\\":
                串缓冲.append(c)
                if nxt:
                    串缓冲.append(nxt)
                i += 2
                continue
            if c == '"':
                字符串们.append((串起始行, "".join(串缓冲)))
                串缓冲.clear()
                在串 = False
                缓冲.append(c)
                i += 1
                continue
            串缓冲.append(c)
            缓冲.append(" ")
            i += 1
            continue
        if c == '"':
            在串 = True
            串起始行 = 行号
            缓冲.append(c)
            i += 1
            continue
        缓冲.append(c)
        i += 1
    代码行们.append("".join(缓冲))
    return 代码行们, 字符串们


def 剥离非代码(文本: str):
    """剥离注释/字符串，保留行结构。返回（代码行们, 字符串们, 注释们）。

    两遍式：① 剥注释（串/字符边界感知）② 剥字符串——内容均替换为空格，
    行号与原文对齐；字符串们/注释们 = [(行号, 内容)]，供「提及」类信息级命中。
    """
    无注, 注释们 = 剥注释(文本)
    代码行们, 字符串们 = 剥字符串(无注)
    return 代码行们, 字符串们, 注释们


def 词法行(行: str) -> list[str]:
    """单行词法：返回 token 表（字符串占位 `"` 保留为 token 供文法对齐）。"""
    return TOKEN_RE.findall(行)


def 查豁免(原行: str, 前行: str = "") -> tuple[bool, str, bool]:
    """豁免注释判定。返回（是否豁免, 理由, 是否理由缺失告警）。

    形态：`// 扫描豁免: 理由`（同一行或前一行）。理由缺失（冒号后为空）=不豁免+告警。
    """
    for 文本 in (原行, 前行):
        m = re.search(r"扫描豁免\s*[:：]\s*(.*)$", 文本)
        if m:
            理由 = m.group(1).strip()
            理由 = re.sub(r"//.*$", "", 理由).strip()
            if 理由:
                return True, 理由, False
            return False, "", True
    return False, "", False


