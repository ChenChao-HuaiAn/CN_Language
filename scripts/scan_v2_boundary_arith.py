def 扫边界移位乘除(ts: list[str], 文件: str, 行号: int, 片段: str) -> list[命中]:
    """R3/R8（边界常量·文本累加）+ R4（移位·`>>` 泛型闭合消歧）+ R5/R6 扫描。"""
    命中们: list[命中] = []
    泛型深 = 0
    for i, t in enumerate(ts):
        前 = ts[i - 1] if i > 0 else None
        后 = ts[i + 1] if i + 1 < len(ts) else None
        # 泛型深度维护（`>>` 消歧：只认构造器名后的 `<`）
        if t == "<" and 前 in 泛型构造器:
            泛型深 += 1
            continue
        if t == ">" and 泛型深 > 0:
            泛型深 -= 1
            continue
        if t == ">>" and 泛型深 >= 2:
            泛型深 -= 2
            continue
        # --- R3 孤立边界常量（含 MIN 分步构造 `x - MAX - 1` 识别） ---
        if t and re.match(r"^\d+$", t) and t in 边界常量表:
            if t == MAX64 and 前 == "-" and 后 == "-" and \
                    i + 2 < len(ts) and ts[i + 2] == "1":
                命中们.append(命中(文件, 行号, "R1c", "MIN 分步构造（x - MAX - 1）", "低", 片段,
                                  "分步防中间溢出·安全惯习"))
            elif 前 in ("-", "&"):
                pass          # 负号/减法的一部分（R1/R2 已处理）或掩码惯习
            else:
                命中们.append(命中(文件, 行号, "R3", f"边界常量·{边界常量表[t]}", "低", 片段,
                                  "边界比较/构造引用·供域核对"))
        # --- R8 文本数值累加：x = x * 基数 + 位 ---
        if (re.match(标识符模式 + r"$", t) and 后 == "=" and i + 5 < len(ts) and
                ts[i + 2] == t and ts[i + 3] == "*" and ts[i + 5] == "+"):
            基数 = ts[i + 4]
            命中们.append(命中(文件, 行号, "R8", "文本数值累加（x = x * 基数 + 位）", "中", 片段,
                              f"基数={基数}·核输入长度上界/溢出预判（19 位 ≥2^63 文本末步超 MAX）"))
        # --- R4 移位 ---
        if t in ("<<", ">>") and 泛型深 == 0:
            if 后 and re.match(数字模式 + r"$", 后):
                数值 = re.match(r"\d+", 后)
                值 = int(数值.group()) if 数值 else 0
                if 值 >= 常量大移位阈:
                    命中们.append(命中(文件, 行号, "R4b", "常量大移位量", "低", 片段,
                                      f"移位量 {值}·核左操作数域位宽（≥ 则编译期硬错误）"))
            elif 后:
                命中们.append(命中(文件, 行号, "R4a", "变量移位量", "中", 片段,
                                  "#474：运行期移位量超宽=错误码 8（自举自杀面）"))
        # --- R5 乘大常量 ---
        if t == "*" and 后 and re.match(数字模式 + r"$", 后):
            数值 = re.match(r"\d+", 后)
            值 = int(数值.group()) if 数值 else 0
            if 值 >= 大常量阈值:
                命中们.append(命中(文件, 行号, "R5", "乘大常量", "中", 片段,
                                  f"×{值}·积可达 2^63 边界面"))
        # --- R6 除 -1 形态（MIN/-1 面；% -1 数学恒 0 不在报） ---
        if t == "/" and 后 == "-" and i + 2 < len(ts) and ts[i + 2] == "1":
            命中们.append(命中(文件, 行号, "R6", "除 -1 形态", "中", 片段,
                              "MIN/-1=错误码 8（#474）·核被除数能否为域 MIN"))
        if t == "/" and 后 == "(" and ts[i + 2:i + 5] == ["0", "-", "1"]:
            命中们.append(命中(文件, 行号, "R6", "除 -1 形态（等价 0-1 写法）", "中", 片段,
                              "MIN/-1=错误码 8（#474）"))
    return 命中们


def 扫一行(ts: list[str], 原行: str, 文件: str, 行号: int,
          代码行们: list[str], 行索引: int) -> list[命中]:
    """单行全部规则族扫描（族函数分工·报告层统一按级别/行号排序）。"""
    片段 = 原行.strip()[:120]
    命中们 = 扫取负面(ts, 文件, 行号, 片段, 代码行们, 行索引)
    命中们.extend(扫边界移位乘除(ts, 文件, 行号, 片段))
    return 命中们


