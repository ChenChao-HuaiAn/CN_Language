def _selftest实跑(编译路径=None):
    """端到端自测：内置合法样本→宿主/v2 双编译；反例=真实 v2 明细注入 stdout/stderr。"""
    结果 = []
    cn = pathlib.Path(编译路径) if 编译路径 else 核心.解析编译器路径("target/cn")
    if not cn.exists():
        结果.append(("端到端：编译器存在（%s）" % cn, False, "缺失——先构建 target/cn"))
        return 结果
    try:
        运行器 = 核心.加载e2e运行器()
    except Exception as e:
        结果.append(("端到端：e2e 运行器加载", False, repr(e)))
        return 结果
    平台 = 核心.探测目标平台()
    if 平台 == "win-x64":
        就绪 = 运行器.确保v2p就绪win(cn, False, "selftest")
    else:
        就绪 = 运行器.确保v2p与运行时就绪(cn, 平台, False, "selftest")
    if 就绪[0] is None:
        结果.append(("端到端：v2p 就绪", False, str(就绪[1])[:200]))
        return 结果
    结果.append(("端到端：v2p 就绪", True, ""))
    临时 = 根 / "target" / "cnsmith_dual_selftest_e2e"
    if 临时.exists():
        shutil.rmtree(临时)
    try:
        样本源 = 临时 / "源码"
        样本源.mkdir(parents=True)
        源码 = ('函数 主() -> 整32 {\n'
                '    整32 甲 = 7;\n    整32 乙 = 3;\n'
                '    打印行("对拍自测 %d", 甲 * 乙 + 1);\n'
                '    返回 0;\n}\n')
        (样本源 / "主.cn").write_text(源码, encoding="utf-8")
        用例输出 = 临时 / "输出"
        用例输出.mkdir()
        ctx = {"运行器": 运行器, "cn": cn, "平台": 平台, "v2p": 就绪[0],
               "用例输出": 用例输出, "用例根": 临时 / "用例", "比stderr": False}
        ctx["用例根"].mkdir()
        样本 = {"名": "selftest_端到端", "源": 样本源 / "主.cn", "来源": "自测",
                "整树": True, "根": 样本源, "入口名": "主.cn", "配置": None,
                "配置问题": ""}
        记录 = 核心.对拍一例(ctx, 样本)
        结果.append(("端到端正例：同源码双编译 rc+stdout 一致（0 分叉）",
                     记录["判定"] == 报告.判定_一致,
                     "%s ｜ %s" % (记录["判定"], 记录.get("详情", ""))))
        if 记录["v2"].get("rc") is not None:
            假v2 = {"rc": 记录["v2"].get("rc"),
                    "stdout": (记录["v2"].get("stdout") or "") + "注入分叉行\n",
                    "stderr": 记录["v2"].get("stderr") or ""}
            判定, 详情, 首, 原因 = 核心.比对两侧(记录["宿主"], 假v2)
            结果.append(("端到端反例：真实 v2 明细注入 stdout 差异 → 检出",
                         判定 == 报告.判定_行为分叉 and bool(首)
                          and 原因 == 报告.原因_STDOUT不一致,
                         "%s %s" % (判定, 详情)))
            假v2b = {"rc": 记录["v2"].get("rc"),
                     "stdout": 记录["v2"].get("stdout") or "",
                     "stderr": (记录["v2"].get("stderr") or "") + "注入stderr分叉\n"}
            判定2, 详情2, 首2, 原因2 = 核心.比对两侧(记录["宿主"], 假v2b,
                                                比stderr=True)
            结果.append(("端到端反例：真实 v2 明细注入 stderr 差异 → 检出（比stderr）",
                         判定2 == 报告.判定_行为分叉 and 首2 is not None
                         and 原因2 == 报告.原因_STDERR不一致,
                         "%s %s" % (判定2, 详情2)))
        else:
            结果.append(("端到端反例：真实 v2 明细可用", False,
                         "v2 未产出运行明细：%s" % (记录["v2"].get("说明", "")[:200])))
    finally:
        shutil.rmtree(临时, ignore_errors=True)
    return 结果
