def selftest(编译路径=None, 实跑=False):
    """对拍轨道自校验。返回 0=全绿 / 1=红。"""
    通过, 失败 = [], []

    def 签(名, 条件, 详情=""):
        if 条件:
            通过.append(名)
        else:
            失败.append((名, 详情))

    _自测判定层(签)
    _自测警告面(签)
    _自测拒因比对(签)
    _自测分类与基线(签)
    _自测轨道与配置(签)
    _自测锁面与双条件(签)
    _自测种子派生(签)
    _自测编译器平台感知(签)
    _自测报告结构(签)
    _自测缓存轴(签)
    _自测缓存轴汇总(签)
    if 实跑:
        for 名, 条件, 详情 in _selftest实跑(编译路径):
            签(名, 条件, 详情)

    for 名 in 通过:
        print("  [通过] %s" % 名)
    for 名, 详情 in 失败:
        print("  [失败] %s%s" % (名, ("—— " + 详情) if 详情 else ""))
    print("selftest: %d 通过 / %d 失败" % (len(通过), len(失败)))
    return 1 if 失败 else 0


