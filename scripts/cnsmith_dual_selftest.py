#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""CN-Smith 对拍轨道·自校验（1130 拆分：判定层 + 轨道级 + 报告结构 + 端到端）。

覆盖（审查 P0-1/P2-2 补强）：
  判定层：正例一致 / stdout 单行篡改 / rc 差 / 缺行 / stderr 开关
  轨道级：跳过>0 → 轨道状态「无效」且 cnsmith_run 汇总判定=无效（exit 2 语义·不当绿）；
         跳过=0 → 完成/全绿
  分类：宿主过 v2 拒（拒绝不一致·方向子类）/ v2 未产 asm（工具链）/ 汇编/链接/
       符号自检原因闭集 / 宿主崩溃（超时 rc=-9）/ 配置退出码不符 / 诊断锚不符
  报告：候选/跳过/一致/建议立案结构 + 首差异文案
  端到端（--实跑）：真实双编译一致；真实 v2 明细注入 stdout 与 stderr 差异均检出
"""
import json
import pathlib
import shutil

import cnsmith_dual as 核心
import cnsmith_dual_report as 报告

根 = 核心.根


def selftest(编译路径=None, 实跑=False):
    """对拍轨道自校验。返回 0=全绿 / 1=红。"""
    通过, 失败 = [], []

    def 签(名, 条件, 详情=""):
        if 条件:
            通过.append(名)
        else:
            失败.append((名, 详情))

    def 明细(rc, stdout="", stderr=""):
        return {"rc": rc, "stdout": stdout, "stderr": stderr}

    # ===== 判定层 =====
    判定, 详情, 首, 原因 = 核心.比对两侧(明细(0, "甲\n乙\n"), 明细(0, "甲\n乙\n"))
    签("正例：双侧 rc+stdout 相同 → 一致（0 分叉）",
       判定 == 报告.判定_一致 and 首 is None and 原因 == 报告.原因_一致,
       "%s %s" % (判定, 详情))
    判定, 详情, 首, 原因 = 核心.比对两侧(明细(0, "甲\n乙\n丙\n"), 明细(0, "甲\nX\n丙\n"))
    签("反例：stdout 第2行篡改 → 行为分叉 + 首差异行=2",
       判定 == 报告.判定_行为分叉 and 首 and 首["行"] == 2
       and 首["类别"] == "stdout" and 原因 == 报告.原因_STDOUT不一致,
       "%s %s" % (判定, 首))
    判定, 详情, 首, 原因 = 核心.比对两侧(明细(0, "甲\n"), 明细(3, "甲\n"))
    签("反例：rc 不同（0 vs 3）→ 行为分叉（原因=退出码不一致）",
       判定 == 报告.判定_行为分叉 and 首 and 首["类别"] == "rc"
       and 原因 == 报告.原因_RC不一致, "%s %s" % (判定, 首))
    判定, 详情, 首, 原因 = 核心.比对两侧(明细(0, "甲\n乙\n"), 明细(0, "甲\n"))
    签("反例：v2 缺行 → 检出（首差异行=2·乙侧=<缺行>）",
       判定 == 报告.判定_行为分叉 and 首 and 首["行"] == 2 and 首["乙"] == "<缺行>",
       "%s %s" % (判定, 首))
    判定1, _, _, _ = 核心.比对两侧(明细(0, "甲\n", "警告甲\n"),
                                明细(0, "甲\n", "警告乙\n"))
    判定2, _, 首2, 原因2 = 核心.比对两侧(明细(0, "甲\n", "警告甲\n"),
                                      明细(0, "甲\n", "警告乙\n"), 比stderr=True)
    签("stderr 按需：默认不参与（一致）｜开启后参与（分叉·原因=stderr不一致）",
       判定1 == 报告.判定_一致 and 判定2 == 报告.判定_行为分叉
       and 首2["类别"] == "stderr" and 原因2 == 报告.原因_STDERR不一致,
       "%s/%s %s" % (判定1, 判定2, 首2))

    # ===== 分类闭集（审查 P2-4：拒绝方向/工具链原因机械可审计）=====
    判定, 原因, 详情 = 核心.v2阶段判定("119-3 v2p 运行失败(退出码1): 语义错误")
    签("宿主过 v2 拒 → 拒绝不一致（原因=宿主过v2拒）",
       判定 == 报告.判定_拒绝不一致 and 原因 == 报告.原因_宿主过v2拒,
       "%s %s" % (判定, 原因))
    判定, 原因, 详情 = 核心.v2阶段判定("119-3 v2p 未生成 target/v2asm.asm")
    签("v2 未产 asm → 工具链/产物异常（原因=v2未生成asm）",
       判定 == 报告.判定_工具链 and 原因 == 报告.原因_v2未产asm,
       "%s %s" % (判定, 原因))
    判定, 原因, _ = 核心.v2阶段判定("1-4 as 汇编失败(退出码1): x")
    签("汇编失败 → 工具链/产物异常（原因=v2汇编失败）",
       判定 == 报告.判定_工具链 and 原因 == 报告.原因_汇编失败, "%s %s" % (判定, 原因))
    判定, 原因, _ = 核心.v2阶段判定("1-5 链接失败(退出码1): x")
    签("链接失败 → 工具链/产物异常（原因=v2链接失败）",
       判定 == 报告.判定_工具链 and 原因 == 报告.原因_链接失败, "%s %s" % (判定, 原因))
    判定, 原因, _ = 核心.v2阶段判定("1-5.5 符号自检失败: map")
    签("符号自检失败 → 工具链/产物异常（原因=v2符号自检失败）",
       判定 == 报告.判定_工具链 and 原因 == 报告.原因_符号自检失败,
       "%s %s" % (判定, 原因))

    # ===== 宿主基线（超时/崩溃/配置不符）=====
    原因, 详情 = 核心.宿主基线判定({"编译rc": 0, "rc": -9}, None, "win-x64")
    签("宿主运行超时/崩溃（rc=-9）→ 宿主基线无效（原因=宿主产物崩溃）",
       原因 == 报告.原因_宿主崩溃, "%s %s" % (原因, 详情))
    原因, 详情 = 核心.宿主基线判定(
        {"编译rc": 0, "rc": 0}, {"预期退出码": 7}, "win-x64")
    签("宿主退出码与用例配置不符 → 宿主基线无效（原因=配置退出码不符）",
       原因 == 报告.原因_配置退出码不符, "%s %s" % (原因, 详情))
    原因, 详情 = 核心.宿主基线判定(
        {"编译rc": 1, "编译输出": "错误: 别的诊断"},
        {"预期编译失败": True, "诊断锚": "不自动解引用"}, "win-x64")
    签("负测诊断锚不符 → 宿主基线无效（原因=配置诊断锚不符）",
       原因 == 报告.原因_配置诊断锚不符, "%s %s" % (原因, 详情))
    原因, 详情 = 核心.宿主基线判定({"编译rc": 1, "编译输出": "错误: 不自动解引用"},
                              {"预期编译失败": True, "诊断锚": "不自动解引用"},
                              "win-x64")
    签("负测诊断锚命中 → 宿主可作基线（走双侧拒绝判定）", 原因 == "", 详情)

    # ===== 建议立案标题 =====
    记录 = {"判定": 报告.判定_行为分叉, "原因": 报告.原因_STDOUT不一致,
            "样本": "selftest样本", "来源": "自测", "详情": "stdout 第 2 行起不一致",
            "首差异": {"行": 2, "类别": "stdout", "甲": "乙", "乙": "X"}}
    标题 = 报告.建议立案标题(记录)
    签("建议立案标题含判定/原因/样本名（不自动写服务端）",
       bool(标题) and "selftest样本" in 标题 and "〔1130对拍〕" in 标题
       and 报告.原因_STDOUT不一致 in 标题, 标题)
    首文案 = 报告.首差异文案({"行": 0, "类别": "rc", "甲": "rc=0", "乙": "rc=3"})
    签("首差异文案：非 stdout/stderr 不编造行号（第0行不出现在文案）",
       "第" not in 首文案 and "rc" in 首文案, 首文案)

    # ===== 预算跳过 + 轨道级状态（P0-1）=====
    跳 = 核心.预算跳过记录(
        [{"名": "预算样本", "源": pathlib.Path("x.cn"), "来源": "自测", "整树": False}], 1)
    签("预算耗尽 → 显式跳过记录（判定=跳过·原因=时间预算耗尽）",
       len(跳) == 1 and 跳[0]["判定"] == 报告.判定_跳过
       and 跳[0]["原因"] == 报告.原因_预算跳过 and "预算" in 跳[0]["详情"],
       str(跳))
    状态, 说明 = 核心.轨道结果状态(一致=1, 候选=0, 跳过=3, 样本数=4)
    签("轨道级：跳过>0 → 状态=无效（覆盖不足·exit 2 语义·不当绿）",
       状态 == "无效" and "覆盖不足" in 说明, "%s %s" % (状态, 说明))
    状态2, _ = 核心.轨道结果状态(一致=4, 候选=0, 跳过=0, 样本数=4)
    签("轨道级：跳过=0 → 状态=完成（全绿路径不受影响）", 状态2 == "完成", 状态2)
    import cnsmith_run                                     # scripts 路径已注入
    汇总, 命中, 无效 = cnsmith_run.汇总判定(
        {"对拍": {"状态": "无效", "命中数": 0, "跳过数": 3, "样本数": 4}})
    签("汇总判定：跳过轨道 → 判定=无效（单轮 exit 2·不得当绿）",
       汇总 == "无效" and 无效 == ["对拍"], "%s %s" % (汇总, 无效))
    汇总2, _, _ = cnsmith_run.汇总判定(
        {"对拍": {"状态": "完成", "命中数": 0, "跳过数": 0, "样本数": 4}})
    签("汇总判定：零候选零跳过 → 全绿", 汇总2 == "全绿", 汇总2)

    # ===== 报告结构 =====
    临时 = 根 / "target" / "cnsmith_dual_selftest"
    if 临时.exists():
        shutil.rmtree(临时)
    try:
        结果们 = [
            {"样本": "s1", "来源": "自测", "源码": "/x/s1.cn", "判定": 报告.判定_一致,
             "原因": 报告.原因_一致, "详情": "", "宿主": {"编译rc": 0, "rc": 0,
             "stdout": "甲\n", "stderr": "", "stdout行数": 1, "stderr行数": 0},
             "v2": {"编译": "通过", "rc": 0, "stdout": "甲\n", "stderr": "",
                    "stdout行数": 1, "stderr行数": 0}, "首差异": None, "建议立案": ""},
            {"样本": "s2", "来源": "自测", "源码": "/x/s2.cn",
             "判定": 报告.判定_行为分叉, "原因": 报告.原因_STDOUT不一致,
             "详情": "stdout 第 1 行起不一致", "宿主": {"编译rc": 0, "rc": 0,
             "stdout": "甲\n", "stderr": "", "stdout行数": 1, "stderr行数": 0},
             "v2": {"编译": "通过", "rc": 0, "stdout": "乙\n", "stderr": "",
                    "stdout行数": 1, "stderr行数": 0},
             "首差异": {"行": 1, "类别": "stdout", "甲": "甲", "乙": "乙"},
             "建议立案": 标题},
            {"样本": "s3", "来源": "自测", "源码": "/x/s3.cn",
             "判定": 报告.判定_跳过, "原因": 报告.原因_预算跳过,
             "详情": "预算耗尽", "宿主": {}, "v2": {}, "首差异": None, "建议立案": ""},
        ]
        json路径, md路径, 候选, 跳过, 一致 = 报告.写差异报告(
            临时, {"轮次": "自测", "时刻": "-", "平台": "自测", "编译器": {}},
            结果们, {"比stderr": False})
        数据 = json.loads(核心.读文本(json路径))
        签("报告结构：候选1/跳过1/一致1 + 建议立案 + 原因字段齐备",
           len(候选) == 1 and len(跳过) == 1 and 一致 == 1
           and len(数据.get("建议立案", [])) == 1
           and 数据["候选"][0]["首差异"]["行"] == 1
           and 数据["候选"][0]["原因"] == 报告.原因_STDOUT不一致,
           "候选=%d 跳过=%d 一致=%d" % (len(候选), len(跳过), 一致))
        签("报告 md 含建议立案/首差异/原因列/跳过节/无效说明",
           "建议立案标题" in 核心.读文本(md路径)
           and "首差异" in 核心.读文本(md路径)
           and "跳过（时间预算/配置不对齐" in 核心.读文本(md路径)
           and "无结果不算过" in 核心.读文本(md路径))
    finally:
        shutil.rmtree(临时, ignore_errors=True)

    # ===== 端到端（可选·--实跑）=====
    if 实跑:
        for 名, 条件, 详情 in _selftest实跑(编译路径):
            签(名, 条件, 详情)

    for 名 in 通过:
        print("  [通过] %s" % 名)
    for 名, 详情 in 失败:
        print("  [失败] %s%s" % (名, ("—— " + 详情) if 详情 else ""))
    print("selftest: %d 通过 / %d 失败" % (len(通过), len(失败)))
    return 1 if 失败 else 0


def _selftest实跑(编译路径=None):
    """端到端自测：内置合法样本→宿主/v2 双编译；反例=真实 v2 明细注入 stdout/stderr。"""
    结果 = []
    cn = pathlib.Path(编译路径) if 编译路径 else 核心.解析编译器路径("target/cn")
    if not cn.exists():
        结果.append(("端到端：编译器存在（%s）" % cn, False, "缺失——先构建 target/cn"))
        return 结果
    try:
        运行器 = 核心.加载e2e运行器()
    except Exception as e:
        结果.append(("端到端：e2e 运行器加载", False, repr(e)))
        return 结果
    平台 = 核心.探测目标平台()
    if 平台 == "win-x64":
        就绪 = 运行器.确保v2p就绪win(cn, False, "selftest")
    else:
        就绪 = 运行器.确保v2p与运行时就绪(cn, 平台, False, "selftest")
    if 就绪[0] is None:
        结果.append(("端到端：v2p 就绪", False, str(就绪[1])[:200]))
        return 结果
    结果.append(("端到端：v2p 就绪", True, ""))
    临时 = 根 / "target" / "cnsmith_dual_selftest_e2e"
    if 临时.exists():
        shutil.rmtree(临时)
    try:
        样本源 = 临时 / "源码"
        样本源.mkdir(parents=True)
        源码 = ('函数 主() -> 整32 {\n'
                '    整32 甲 = 7;\n    整32 乙 = 3;\n'
                '    打印行("对拍自测 %d", 甲 * 乙 + 1);\n'
                '    返回 0;\n}\n')
        (样本源 / "主.cn").write_text(源码, encoding="utf-8")
        用例输出 = 临时 / "输出"
        用例输出.mkdir()
        ctx = {"运行器": 运行器, "cn": cn, "平台": 平台, "v2p": 就绪[0],
               "用例输出": 用例输出, "用例根": 临时 / "用例", "比stderr": False}
        ctx["用例根"].mkdir()
        样本 = {"名": "selftest_端到端", "源": 样本源 / "主.cn", "来源": "自测",
                "整树": True, "根": 样本源, "入口名": "主.cn", "配置": None,
                "配置问题": ""}
        记录 = 核心.对拍一例(ctx, 样本)
        结果.append(("端到端正例：同源码双编译 rc+stdout 一致（0 分叉）",
                     记录["判定"] == 报告.判定_一致,
                     "%s ｜ %s" % (记录["判定"], 记录.get("详情", ""))))
        if 记录["v2"].get("rc") is not None:
            假v2 = {"rc": 记录["v2"].get("rc"),
                    "stdout": (记录["v2"].get("stdout") or "") + "注入分叉行\n",
                    "stderr": 记录["v2"].get("stderr") or ""}
            判定, 详情, 首, 原因 = 核心.比对两侧(记录["宿主"], 假v2)
            结果.append(("端到端反例：真实 v2 明细注入 stdout 差异 → 检出",
                         判定 == 报告.判定_行为分叉 and bool(首)
                          and 原因 == 报告.原因_STDOUT不一致,
                         "%s %s" % (判定, 详情)))
            假v2b = {"rc": 记录["v2"].get("rc"),
                     "stdout": 记录["v2"].get("stdout") or "",
                     "stderr": (记录["v2"].get("stderr") or "") + "注入stderr分叉\n"}
            判定2, 详情2, 首2, 原因2 = 核心.比对两侧(记录["宿主"], 假v2b,
                                                比stderr=True)
            结果.append(("端到端反例：真实 v2 明细注入 stderr 差异 → 检出（比stderr）",
                         判定2 == 报告.判定_行为分叉 and 首2 is not None
                         and 原因2 == 报告.原因_STDERR不一致,
                         "%s %s" % (判定2, 详情2)))
        else:
            结果.append(("端到端反例：真实 v2 明细可用", False,
                         "v2 未产出运行明细：%s" % (记录["v2"].get("说明", "")[:200])))
    finally:
        shutil.rmtree(临时, ignore_errors=True)
    return 结果
