"""CN-Smith 生成器·族程序模板（1109 体量红线「先拆再加」拆出面·1740 扩）

归属与分工（cnsmith_gen.py 996→1100+ 行触警戒线，1740 扩三族前先拆）：
  cnsmith_gen.py            折叠保护域 + Gen 随机语句面 + 注入器 + selftest/CLI
  cnsmith_gen_families.py   族名们 + 族程序（本文件：七族固定模板·随机只选变体）

族轨道设计（1022·#1398 立制·1740 扩面）：
  混合面 seed%8 轮转「标量 + 七族」——连续 8 个 seed 覆盖全生成面。四族用于让
  #1393~#1397（v2 枚举宽度/重载后缀/默认参数/NUL 转义）在自动对拍轨道显形，
  修复前对拍与矩阵轨道对这些族预期红（红在明处·勿误判工具回归）。
  1740 扩三族（#1735/#1737/#1739 锁面·2026-10-27 采样轮四缺陷全部由手动探针
  挖出、自动轨道零覆盖的实证收口）：
    枚举默认初始化    #1735→#1760 立法反转（2026-10-28 用户裁决乙案）：原
                      `状态 s;` 无初值读 0 形态随枚举纳入 def-init 登记面
                      转为「声明+立即赋值」正形态（先赋值后读放行锁·负形态
                      归 1604 E2E+对拍内置拒绝锁）
    方法句柄链        #1737：类 A 方法返回类 B → `.方法().方法()` 单链+三级链+混链
    结构体拷贝        #1739：`点 备份 = 路[1];` 声明下标源拷贝+嵌套成员链下标源
  #1736 聚合比较负形态（预期双侧一致拒）不入随机合法面（「只生成合法程序」
  契约——宿主执法后拒），走对拍内置双侧拒绝锁（cnsmith_dual_samples.1740 段）。
  三新族在任务/1735~1739 修复集成 develop 前对拍轨道预期红（红在明处·同 1022 先例）。

合法性契约（847 收口）：全部族程序=宿主可编译合法程序（值错由对拍轨道显形）。
"""
import random

# 族序=混合面 seed%8 轮转序（1~7 依次命中；0=标量面）——追加族必须尾插
# （防既有 seed 的族映射漂移·selftest 结构断言按序计数）
族名们 = ("枚举数组", "重载后缀", "默认参数", "转义字符串",
          "枚举默认初始化", "方法句柄链", "结构体拷贝")


def 族程序(族名, seed):
    """族完整程序生成（确定性：族内 rng=seed*1009+族序）。

    返回源码带 `// 族=<名>` 标记（selftest 覆盖断言消费）。每族两变体，
    全部为宿主可编译的合法程序；值取小域确定形态，避免常量折叠/移位保护面。
    """
    rng = random.Random(seed * 1009 + 族名们.index(族名))
    if 族名 == "枚举数组":
        if rng.random() < 0.5:
            return r'''// 族=枚举数组
枚举 颜色 { 红, 绿, 蓝 }
函数 枚举和(颜色[3] 表) -> 整32 {
    返回 整32(表[0]) + 整32(表[1]) + 整32(表[2]);
}
函数 主() -> 整32 {
    颜色[3] 表 = {颜色.红, 颜色.绿, 颜色.蓝};
    打印(整32(表[0]), " ", 整32(表[1]), " ", 整32(表[2]));
    打印(枚举和(表));
    返回 0;
}
'''
        return r'''// 族=枚举数组
枚举 方向 { 上 = -1, 中 = 0, 下 = 1 }
函数 主() -> 整32 {
    方向[3] 表;
    表[0] = 方向.上;
    表[1] = 方向.中;
    表[2] = 方向.下;
    循环 (整32 i = 0; i < 3; i++) {
        打印(整32(表[i]), " ");
    }
    返回 0;
}
'''
    if 族名 == "重载后缀":
        if rng.random() < 0.5:
            return r'''// 族=重载后缀
函数 取(整32 x) -> 整32 { 返回 x + 1; }
函数 取(整64 x) -> 整64 { 返回 x + 2L; }
函数 述(浮32 x) -> 整32 { 返回 1; }
函数 述(浮64 x) -> 整32 { 返回 2; }
函数 主() -> 整32 {
    打印(取(1), " ", 取(1L));
    打印(述(1.5f), " ", 述(1.5));
    返回 0;
}
'''
        return r'''// 族=重载后缀
函数 选(正32 x) -> 整32 { 返回 1; }
函数 选(正64 x) -> 整32 { 返回 2; }
函数 取(整32 x) -> 整32 { 返回 x + 1; }
函数 取(整64 x) -> 整64 { 返回 x + 2L; }
函数 主() -> 整32 {
    打印(选(1U), " ", 选(1UL));
    打印(取(1), " ", 取(1L));
    返回 0;
}
'''
    if 族名 == "默认参数":
        if rng.random() < 0.5:
            return r'''// 族=默认参数
常量 基 = 5;
函数 算(整32 a = 1 + 2, 整32 b = 基) -> 整32 {
    返回 a + b;
}
函数 主() -> 整32 {
    打印(算());
    打印(算(10));
    返回 0;
}
'''
        return r'''// 族=默认参数
类 盒 {
公开:
    整32 值;
    函数 盒(整32 n = 2 + 3) { 值 = n; }
}
函数 主() -> 整32 {
    盒 b = 盒();
    打印(b.值);
    返回 0;
}
'''
    if 族名 == "转义字符串":
        if rng.random() < 0.5:
            return r'''// 族=转义字符串
函数 主() -> 整32 {
    字符串 s = "a\0b";
    打印(字符串长度(s), " ", s[0]);
    字符串 r = 原始"a\tb";
    打印(字符串长度(r));
    返回 0;
}
'''
        return r'''// 族=转义字符串
函数 主() -> 整32 {
    字符串 甲 = 多行"""第一行
第二行""";
    字符串 乙 = 原始多行"""甲\n乙""";
    打印(字符串长度(甲), " ", 字符串长度(乙));
    返回 0;
}
'''
    # -----------------------------------------------------------------
    # 1740 扩面三族（#1735/#1737/#1739 锁面）：均为宿主可编译合法程序
    #   （合法性契约=宿主编译通过）；v2 侧分叉=对拍轨道命中面，修复集成
    #   develop 前预期红（红在明处·同 1022 先例）。
    # -----------------------------------------------------------------
    if 族名 == "枚举默认初始化":
        # #1760 立法反转：枚举无初值声明读已双侧拒（1604 锁面），随机合法面
        #   转「声明+立即赋值」正形态（先赋值后读+域值回读·防执法误伤）。
        if rng.random() < 0.5:
            return r'''// 族=枚举默认初始化
枚举 状态 { 停, 行 }
函数 污染() -> 整32 {
    整64 a = 111111;
    整64 b = 222222;
    整64 c = 333333;
    返回 整32(a + b + c);
}
函数 主() -> 整32 {
    污染();
    状态 s = 状态.停;
    状态 t = 状态.行;
    打印(整32(s), " ", 整32(t));
    返回 0;
}
'''
        return r'''// 族=枚举默认初始化
枚举 档位 { 低 = -1, 中 = 0, 高 = 1 }
函数 主() -> 整32 {
    档位 g = 档位.中;
    打印(整32(g));
    g = 档位.高;
    打印(整32(g));
    档位 h = 档位.低;
    打印(整32(h));
    返回 0;
}
'''
    if 族名 == "方法句柄链":
        if rng.random() < 0.5:
            return r'''// 族=方法句柄链
类 轮子 {
公开:
    函数 数目() -> 整32 {
        返回 4;
    }
}
类 车 {
公开:
    函数 轮子部() -> 轮子 {
        轮子 w;
        返回 w;
    }
}
函数 主() -> 整32 {
    车 c;
    打印(c.轮子部().数目());
    返回 0;
}
'''
        return r'''// 族=方法句柄链
类 核心 {
公开:
    函数 编号() -> 整32 {
        返回 42;
    }
}
类 中枢 {
公开:
    函数 核心部() -> 核心 {
        核心 n;
        返回 n;
    }
}
类 系统 {
公开:
    函数 中枢部() -> 中枢 {
        中枢 m;
        返回 m;
    }
}
结构体 记录 { 整32 v; }
类 仓库 {
公开:
    函数 取() -> 记录 {
        记录 d;
        d.v = 7;
        返回 d;
    }
}
类 外壳 {
公开:
    函数 仓库部() -> 仓库 {
        仓库 w;
        返回 w;
    }
}
函数 主() -> 整32 {
    系统 s;
    打印(s.中枢部().核心部().编号());
    外壳 o;
    打印(o.仓库部().取().v);
    返回 0;
}
'''
    if 族名 == "结构体拷贝":
        if rng.random() < 0.5:
            return r'''// 族=结构体拷贝
结构体 点 { 整32 x; 整32 y; }
函数 造点(整32 a, 整32 b) -> 点 {
    点 p;
    p.x = a;
    p.y = b;
    返回 p;
}
函数 主() -> 整32 {
    点[3] 路;
    路[1] = 造点(5, 6);
    点 备份 = 路[1];
    打印(备份.x, " ", 备份.y);
    备份.x = 100;
    打印(路[1].x);
    返回 0;
}
'''
        return r'''// 族=结构体拷贝
结构体 点 { 整32 x; 整32 y; }
结构体 外壳 { 点 内; 点[3] 路; }
函数 造点(整32 a, 整32 b) -> 点 {
    点 p;
    p.x = a;
    p.y = b;
    返回 p;
}
函数 主() -> 整32 {
    外壳 外;
    外.路[2] = 造点(9, 10);
    点 快照 = 外.路[2];
    打印(快照.x, " ", 快照.y);
    外.内 = 造点(7, 8);
    点 摹本 = 外.内;
    打印(摹本.y);
    返回 0;
}
'''
    raise AssertionError("闭集外族名：%s" % 族名)   # 穷举断言（miss 不可静默）
