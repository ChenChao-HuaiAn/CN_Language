def 缓存双跑判定(跑1, 跑2, 统计1, 统计2, 验证行, stderr1净, stderr2净, 比stderr):
    """双跑结果 → (判定, 原因, 详情, 首差异)。

    判定顺序（先显形最精确原因）：统计缺失（跳过）→ 验证错误行 → 命中缺失
    → 损坏回退 → 缓存环境编译失败 → rc → stdout → stderr（比stderr）。
    统计行缺失=基础设施异常非缓存分叉，显式跳过不当绿（任务纪律）。"""
    if 统计1 is None or 统计2 is None:
        缺 = "首跑" if 统计1 is None else "命中跑"
        return (报告.判定_跳过, 报告.原因_缓存统计缺失,
                "%s stderr 无 [AST 缓存] 统计行（CN_AST_CACHE_STATS=1 未生效或编译器异常）"
                "——显式跳过·不当绿" % 缺, None)
    if 验证行:
        return (报告.判定_缓存分叉, 报告.原因_缓存验证失败,
                "命中跑验证显形（反序列化 vs 重解析不符）：%s"
                % 报告.截断("；".join(验证行), 400),
                {"行": 0, "类别": "缓存验证", "甲侧": "宿主首跑", "乙侧": "宿主命中跑",
                 "甲": "无验证行", "乙": 报告.截断(验证行[0], 200)})
    if 统计2["命中"] < 1:
        return (报告.判定_缓存分叉, 报告.原因_缓存命中缺失,
                "命中跑 命中=%d（须≥1：空缓存首编后二次同源码编译必须命中）" % 统计2["命中"],
                {"行": 0, "类别": "缓存命中", "甲侧": "宿主首跑", "乙侧": "宿主命中跑",
                 "甲": "首建=%d" % 统计1["首建"], "乙": "命中=%d" % 统计2["命中"]})
    if 统计2["损坏回退"] != 0:
        return (报告.判定_缓存分叉, 报告.原因_缓存损坏回退,
                "命中跑 损坏回退=%d（须=0：命中条目损坏/版本不符=缓存面缺陷）"
                % 统计2["损坏回退"],
                {"行": 0, "类别": "缓存损坏", "甲侧": "宿主首跑", "乙侧": "宿主命中跑",
                 "甲": "损坏回退=0", "乙": "损坏回退=%d" % 统计2["损坏回退"]})
    if 跑1.get("编译rc") != 0 or 跑2.get("编译rc") != 0:
        return (报告.判定_缓存分叉, 报告.原因_缓存编译失败,
                "缓存环境编译失败：首跑编译rc=%s ｜ 命中跑编译rc=%s（主轴无缓存环境"
                "同源码编译通过=加缓存后行为变了）" % (跑1.get("编译rc"), 跑2.get("编译rc")),
                {"行": 0, "类别": "编译判据", "甲侧": "宿主首跑", "乙侧": "宿主命中跑",
                 "甲": "编译rc=%s" % 跑1.get("编译rc"),
                 "乙": "编译rc=%s" % 跑2.get("编译rc")})
    if 跑1.get("rc") != 跑2.get("rc"):
        return (报告.判定_缓存分叉, 报告.原因_缓存输出不一致,
                "退出码不一致：首跑 rc=%s ｜ 命中跑 rc=%s" % (
                    跑1.get("rc"), 跑2.get("rc")),
                {"行": 0, "类别": "rc", "甲侧": "宿主首跑", "乙侧": "宿主命中跑",
                 "甲": "rc=%s" % 跑1.get("rc"), "乙": "rc=%s" % 跑2.get("rc")})
    首 = 核心.首行差异(跑1.get("stdout", ""), 跑2.get("stdout", ""), "stdout")
    if 首 is not None:
        首["甲侧"], 首["乙侧"] = "宿主首跑", "宿主命中跑"
        return (报告.判定_缓存分叉, 报告.原因_缓存输出不一致,
                "stdout 第 %d 行起不一致：首跑 %r ｜ 命中跑 %r" % (首["行"], 首["甲"], 首["乙"]),
                首)
    if 比stderr:
        首 = 核心.首行差异(stderr1净, stderr2净, "stderr")
        if 首 is not None:
            首["甲侧"], 首["乙侧"] = "宿主首跑", "宿主命中跑"
            return (报告.判定_缓存分叉, 报告.原因_缓存输出不一致,
                    "stderr（剥离缓存行）第 %d 行起不一致：首跑 %r ｜ 命中跑 %r"
                    % (首["行"], 首["甲"], 首["乙"]), 首)
    return (报告.判定_一致, 报告.原因_一致,
            "缓存双跑一致：命中跑 命中=%d 损坏回退=0，rc+stdout（%s）逐行相等"
            % (统计2["命中"], "+stderr" if 比stderr else "stderr未参与"), None)


