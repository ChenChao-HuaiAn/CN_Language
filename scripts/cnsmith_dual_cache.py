def 缓存预算跳过(待们, 预算):
    """预算耗尽剩余样本 → 缓存轴跳过记录（不当绿；复用主轴 跳过记录 再覆盖轴面）。"""
    记录们 = []
    for 样本, _主 in 待们:
        记录 = dict(核心.跳过记录(样本, 预算, 报告.原因_预算跳过, ""),
                    样本=样本["名"] + 记录后缀,
                    配置="", 配置类型=样本.get("配置类型", "") if 样本.get("配置") else "",
                    轴=轴名, 缓存轴=True,
                    v2={"编译": "未参与（缓存轴乙侧·v2 不适用）"})
        记录们.append(记录)
    return 记录们


def 缓存汇总面(记录们, 上限, 排除数):
    """缓存轴记录 → 汇总 dict（轨道结果/摘要行/报告节的数据源）。"""
    跳过们 = [r for r in 记录们 if r["判定"] == 报告.判定_跳过]
    return {"启用": True, "上限": 上限, "排除数": 排除数,
            "样本数": len(记录们),
            "一致": sum(1 for r in 记录们 if r["判定"] == 报告.判定_一致),
            "命中": sum(1 for r in 记录们
                      if r["判定"] not in (报告.判定_一致, 报告.判定_跳过)),
            "跳过": len(跳过们),
            "统计缺失": sum(1 for r in 跳过们 if r.get("原因") == 报告.原因_缓存统计缺失)}


def 轨道_缓存对拍(ctx, 样本们, 主结果们, 上限, 截止, 预算):
    """缓存对拍轴轨道面：选样→（并发）双跑→汇总。返回 (记录们, 汇总dict)。

    选样=主轴结果中「宿主编译通过」的前 上限 个样本（宿主拒绝样本无缓存写入
    面·排除数显形进汇总）。预算沿用对拍预算秒截止（同源 monotonic）。"""
    上限 = max(0, int(上限))
    if 上限 <= 0:
        return [], {"启用": False, "说明": "缓存对拍样本=0（本轴关闭）"}
    前缀 = 样本们[:上限]
    主索引 = {r["样本"]: r for r in 主结果们}
    候选 = [(s, 主索引[s["名"]]) for s in 前缀
            if s["名"] in 主索引 and 主索引[s["名"]].get("宿主", {}).get("编译rc") == 0]
    排除数 = len(前缀) - len(候选)
    记录们 = []
    缓存根 = ctx["缓存根"]
    并发 = max(1, ctx.get("并发", 1))
    待 = list(候选)
    while 待:
        if 截止 is not None and time.monotonic() >= 截止:
            记录们.extend(缓存预算跳过(待, 预算))
            待 = []
            break
        批, 待 = 待[:并发], 待[并发:]
        with concurrent.futures.ThreadPoolExecutor(max_workers=len(批)) as 池:
            记录们.extend(池.map(
                lambda p: 安全缓存双跑(ctx, p[0], p[1], 缓存根), 批))
    汇总 = 缓存汇总面(记录们, 上限, 排除数)
    if 排除数:
        print("  [对拍·缓存] ⚠ 前 %d 样本中 %d 个宿主未编译通过（无缓存写入面·排除显形）"
              % (len(前缀), 排除数), flush=True)
    print("  [对拍·缓存] 完成：样本 %d·一致 %d·分叉 %d·跳过 %d"
          % (汇总["样本数"], 汇总["一致"], 汇总["命中"], 汇总["跳过"]), flush=True)
    return 记录们, 汇总
