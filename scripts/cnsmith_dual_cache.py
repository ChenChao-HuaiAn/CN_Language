# 统计行格式唯一来源=driver_ast_cache.cpp reportAstCacheStats（改格式须双侧同步）
_统计行模式 = re.compile(
    r"\[AST 缓存\] 命中=(\d+) 首建=(\d+) 失效重建=(\d+) 损坏回退=(\d+) "
    r"写入=(\d+) 写失败=(\d+) 序列化失败=(\d+)")
_统计键 = ("命中", "首建", "失效重建", "损坏回退", "写入", "写失败", "序列化失败")
_验证行词面 = "[AST 缓存验证]"  # 验证通道错误行唯一词面（driver 两处 fprintf 均「错误:」前缀）
_缓存行词面 = "[AST 缓存"       # 统计/警告/验证三类缓存基础设施输出的公共前缀
轴名 = "缓存对拍"
记录后缀 = "#缓存"


# =====================================================================
# 统计行解析与缓存行剥离（纯函数·selftest 直测）
