"""CN-Smith 对拍轨道·缓存对拍轴（#1556·宿主 AST 模块缓存二次编译对拍）。

背景（#1556·2026-10-24）：1142 宿主 AST 模块缓存（CN_AST_CACHE_DIR/CN_NO_AST_CACHE/
CN_AST_CACHE_STATS/CN_AST_CACHE_VERIFY 环境开关·src/cn_compiler/driver/driver_ast_cache.cpp）
的两件 P0 缺陷全靠手动探针发现——自动面零覆盖「二次编译对拍」。本轴把
「同源码同编译器连跑两次宿主 build+运行」挂进对拍轨道：第 1 次=首编（写缓存），
第 2 次=命中跑（附加 CN_AST_CACHE_VERIFY=1·命中后反序列化 vs 重解析打印比对，
编译器自己显形），断言命中跑 命中≥1、损坏回退=0、两侧 rc/stdout（stderr 按
--对拍比stderr·剥离缓存行后）逐行一致。

**边界：v2 侧不跑缓存轴**——v2p 是另一套编译链（CN语言编译器v2 自举实现·
无 CN_AST_CACHE_* 环境面），本轴只测宿主（src/ C++ 实现）AST 缓存面；
对拍主轴（宿主×v2 行为对拍）不受影响，缓存轴记录仅追加进结果面（样本名带
「#缓存」后缀·命中归档桶=缓存/）。

判定（闭集·miss 不可静默）：
  一致         双跑编译均过、命中跑 命中≥1 且 损坏回退=0、rc/stdout（+stderr·
               剥离缓存行后）逐行相等、无验证错误行
  缓存分叉     任一不符（原因细分：缓存验证错误行/缓存二次未命中/损坏回退非零/
               输出不一致/缓存环境编译失败）——分叉候选计红·归档进 命中/缓存/
  跳过         统计行缺失（CN_AST_CACHE_STATS=1 未生效或编译器异常——显式计数
               +黄字提示·禁当绿）/预算耗尽（沿用对拍预算秒机制·轨道置无效）
  抽查异常     单样本执行异常（隔离·不中断整轮）

性能护栏：只对对拍样本前 N（--缓存对拍样本·默认 12）个中「主轴宿主编译通过」
的样本执行（宿主拒绝样本无缓存写入面·排除数显形）；预算沿用对拍预算秒
（截止同源 monotonic·耗尽样本显式计跳过→轨道无效·无结果不算过）。

自校验：python scripts/cnsmith_dual.py --selftest（判定层正/反例=本模块
  纯函数·含于 cnsmith_dual_selftest._自测缓存轴；--实跑 附加真实缓存双跑端到端）。
"""
