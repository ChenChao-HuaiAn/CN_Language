def 缓存双跑环境(缓存目录):
    """缓存轴注入环境：独立缓存目录（防跨样本串扰）+ 统计开 + 显式压 CN_NO_AST_CACHE=0
    （防外部逃生门禁缓存致命中=0 全员误报——禁用逃生门只对轴外生效）。"""
    return {"CN_AST_CACHE_DIR": str(缓存目录),
            "CN_AST_CACHE_STATS": "1",
            "CN_NO_AST_CACHE": "0"}


def 组装缓存记录(样本, 主记录, 跑1, 跑2, 比stderr):
    """双跑明细 → 缓存轴记录 dict（兼容 写差异报告/记录速记/命中归档 结构面）。"""
    名 = 样本["名"]
    编译stderr1 = 跑1.get("编译stderr", "")
    编译stderr2 = 跑2.get("编译stderr", "")
    统计1 = 解析缓存统计行(编译stderr1)
    统计2 = 解析缓存统计行(编译stderr2)
    _, 行2 = 剥离缓存行(编译stderr2)
    验证行 = 验证错误行们(行2)
    stderr1净, _ = 剥离缓存行(跑1.get("stderr", ""))
    stderr2净, _ = 剥离缓存行(跑2.get("stderr", ""))
    判定, 原因, 详情, 首差 = 缓存双跑判定(
        跑1, 跑2, 统计1, 统计2, 验证行, stderr1净, stderr2净, 比stderr)
    if 判定 == 报告.判定_跳过 and 原因 == 报告.原因_缓存统计缺失:
        # 任务纪律：统计行解析失败=显式计数跳过并黄字提示，禁当绿
        print("  [对拍·缓存] ⚠ 样本 %s%s 统计行缺失（显式跳过·不当绿）" % (名, 记录后缀),
              flush=True)
    记录 = {
        "样本": 名 + 记录后缀, "来源": 样本["来源"], "源码": str(样本["源"]),
        "源": str(样本["源"]), "整树": bool(样本.get("整树")),
        "入口": 主记录.get("入口", "主.cn"),
        "配置": "", "配置类型": 样本.get("配置类型", "") if 样本.get("配置") else "",
        "轴": 轴名, "缓存轴": True,
        "判定": 判定, "原因": 原因, "详情": 详情, "首差异": 首差,
        # 宿主=首跑侧｜v2 键位=命中跑侧（报告表列复用·文案显形 v2 不参与本轴）
        "宿主": {"编译rc": 跑1.get("编译rc"), "rc": 跑1.get("rc"),
                 "stdout": 报告.截断(跑1.get("stdout", "")),
                 "stdout行数": len((跑1.get("stdout") or "").splitlines()),
                 "stderr": 报告.截断(stderr1净),
                 "stderr行数": len(stderr1净.splitlines()),
                 "编译输出": 报告.截断(编译stderr1, 2000)},
        "v2": {"编译": "缓存命中跑（缓存轴乙侧·v2 不参与本轴）", "rc": 跑2.get("rc"),
               "stdout": 报告.截断(跑2.get("stdout", "")),
               "stdout行数": len((跑2.get("stdout") or "").splitlines()),
               "stderr": 报告.截断(stderr2净),
               "stderr行数": len(stderr2净.splitlines()),
               "编译输出": 报告.截断(编译stderr2, 2000)},
        "缓存统计": {"首跑": 统计1, "命中跑": 统计2},
        "缓存验证行们": 验证行,
        "建议立案": "",
    }
    记录["建议立案"] = 缓存建议立案标题(记录)
    return 记录


def 缓存双跑一例(ctx, 样本, 主记录, 缓存根):
    """缓存轴单样本：同源码同编译器连跑两次宿主 build+运行。

    独立临时 CN_AST_CACHE_DIR=缓存根/<样本名>（跑前清空防跨样本串扰）；
    第 1 次=首编（写缓存），第 2 次=命中跑+CN_AST_CACHE_VERIFY=1（编译器
    反序列化 vs 重解析自比对显形）。v2 侧不参与（边界见模块 docstring）。"""
    名 = 样本["名"]
    缓存目录 = 缓存根 / 名
    if 缓存目录.exists():
        shutil.rmtree(缓存目录)
    登记 = ctx["用例根"] / 名                  # 主轴已登记（轨道_对拍 先跑主轴）
    入口名 = 主记录.get("入口", "主.cn")
    环境基 = 缓存双跑环境(缓存目录)
    跑1 = 核心.宿主一侧(ctx, 登记, 名, 入口名, 环境变量=dict(环境基))
    跑2 = 核心.宿主一侧(ctx, 登记, 名, 入口名,
                     环境变量=dict(环境基, CN_AST_CACHE_VERIFY="1"))
    return 组装缓存记录(样本, 主记录, 跑1, 跑2, ctx["比stderr"])


def 安全缓存双跑(ctx, 样本, 主记录, 缓存根):
    """单样本异常隔离：异常转「抽查异常」记录，不中断整轮。
    （与 cnsmith_dual.安全对拍 同构第二处·形态异构待第三处归纳。）"""
    try:
        return 缓存双跑一例(ctx, 样本, 主记录, 缓存根)
    except Exception as e:                  # 隔离面：任何异常不炸整轮（对齐主轴语义）
        记录 = {"样本": 样本["名"] + 记录后缀, "来源": 样本["来源"],
                "源码": str(样本["源"]), "源": str(样本["源"]),
                "整树": bool(样本.get("整树")), "入口": 主记录.get("入口", "主.cn"),
                "配置": "", "配置类型": "", "轴": 轴名, "缓存轴": True,
                "判定": 报告.判定_抽查异常, "原因": 报告.原因_抽查异常,
                "详情": "缓存双跑执行异常：%r" % (e,),
                "宿主": {}, "v2": {}, "首差异": None,
                "缓存统计": {}, "缓存验证行们": [], "建议立案": ""}
        记录["建议立案"] = 缓存建议立案标题(记录)
        return 记录


