def 解析缓存统计行(stderr文本):
    """stderr → 统计 dict（命中/首建/…七字段）；无行/坏行=None。

    miss 不可静默：返回 None 是显式哨兵，调用方必须分流（计跳过黄字·禁当绿）。"""
    m = _统计行模式.search(stderr文本 or "")
    if not m:
        return None
    return dict(zip(_统计键, (int(x) for x in m.groups())))


def 剥离缓存行(文本):
    """剥离含缓存基础设施词面的行（统计/警告/验证——非程序行为输出）。

    返回 (剩余文本, 缓存行们)；缓存行们供验证错误检测与命中归档证据。"""
    剩余, 缓存行们 = [], []
    for 行 in (文本 or "").splitlines():
        (缓存行们 if _缓存行词面 in 行 else 剩余).append(行)
    return "\n".join(剩余), 缓存行们


def 验证错误行们(缓存行们):
    """缓存行中属于 [AST 缓存验证] 错误通道的行（验证模式命中后比对显形）。"""
    return [行 for 行 in 缓存行们 if _验证行词面 in 行]


