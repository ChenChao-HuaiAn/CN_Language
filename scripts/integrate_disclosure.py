"""integrate_disclosure.py —— 点名放行披露机械化（818·known-red 放行路径的强制披露闸门）。

背景（818 立案）：2026-10-13 22:33 起约 36h 三平台零绿，存量红（715/770/777/802/839/
870/826/628 等）致全量恒红，所有新头实际全靠『已知红点名放行』（--allow-known-red/
--allow-pool-red）入 develop。integrate 放行判定明示义务『使用责任=发起机·广播披露·
不实可 revert』，但抽查 7 头仅 2 头在提交信息披露（728a b57a080dc 实锤：红 3 例全命中
点名清单放行·提交信息零披露行）——披露义务无机械抓手=漏披露常态化。

机制（单一判据·本模块唯一权威）：放行前核链顶（HEAD·将推送 develop 的提交）提交信息：
  ① 含标记〔点名放行〕——披露段存在；
  ② 披露段（标记起至信息末尾）含全部红例名——红例清单非空壳（禁只写标记）；
  任一不满足=拒（调用方以拦截返回；修复=把披露段写入本分支最新提交后重推重跑集成）。
定性引用/点名依据两句=人事（机器不可判）；机械面只核「段存在+红例名齐」两钩。

设计约束（对齐 AGENTS §3 / ai-code-quality-guard）：
- 纯函数零 IO（提交信息由调用方读取传入）——selftest 零真 git；
- miss 不静默：提交信息不可读（None/空）= 拒（证据不可读≠无披露·宁拦勿放）；
- 判据单点：标记/判据只在本模块定义，integrate 四个 known-red 放行消费点共用（禁第二套）。

调用点（scripts/integrate.py 全部 known-red 放行路径——链顶披露检查 粘合读取）：
- 全量门禁 win 分步串行复验放行（591-a）；全量门禁 linux 串行复验放行（564-a）；
- 池轮询预验红全点名放行（216）；云端预验门禁 ssh 直发红全点名放行（216 同判据）。
"""
from __future__ import annotations

# 唯一合法披露标记（判据单点——改此串=改全链判据；拒因文案内嵌同串供复制）
点名放行标记 = "〔点名放行〕"


def 点名放行披露检查(提交信息: str | None, 红例们: list) -> str | None:
    """披露闸门纯函数：返回 None=披露齐备（可放行）；非 None=拒因（拦截说明文本）。

    判据三钩（显式枚举·每拒态给出路）：
      ①红例清单非空——空清单=未显形红（868 同口径），放行前置自证；
      ②提交信息可读且含标记〔点名放行〕；
      ③披露段（标记起至信息末尾）含全部红例名。
    注：提交信息=链顶（将推送 develop 的提交）完整信息；红例们=本轮红用例名清单。
    """
    if not 红例们:
        return ("点名放行披露检查不通过（818）：红例清单为空——空清单=未显形红"
                "（868 口径），禁止走披露放行路径；核 runner 日志/e2e明细定界失败用例。")
    if 提交信息 is None or not 提交信息.strip():
        return ("点名放行披露检查不通过（818）：链顶提交信息不可读（git 读取失败/空）"
                "——miss 不静默：证据不可读≠无披露，宁拦勿放；检查仓库状态后重试。")
    段首 = 提交信息.find(点名放行标记)
    if 段首 == -1:
        return ("点名放行披露检查不通过（818）：链顶提交信息无标记〔点名放行〕——"
                "请把披露段（标记〔点名放行〕+点名依据+红例清单+定性引用）写入本分支最新提交"
                "（git commit --amend 或补一提交）后重推重跑集成；本轮红例："
                + "、".join(str(u) for u in 红例们) + "。")
    披露段 = 提交信息[段首:]
    缺失 = [str(红例名) for 红例名 in 红例们 if str(红例名) not in 披露段]
    if 缺失:
        return ("点名放行披露检查不通过（818）：〔点名放行〕段未列红例名 "
                + "、".join(缺失)
                + "——红例清单非空壳为披露要求（段=标记起至信息末尾）；补齐后重推重跑集成。")
    return None


# ===== 内置自测（python scripts/integrate_disclosure.py）=====
if __name__ == "__main__":
    断言们 = [
        # (提交信息, 红例们, 期望过否)
        ("〔点名放行〕红例 501_某用例（已定性·非本批引入）", ["501_某用例"], True),
        ("正文若干\n〔点名放行〕红例：524_条件编译双编译、715_x", ["524_条件编译双编译", "715_x"], True),
        ("无任何标记的提交信息", ["501_某用例"], False),                      # 无标记=拒
        ("〔点名放行〕只写标记不列红例名", ["501_某用例"], False),            # 空壳段=拒
        ("前文提过 501_某用例\n〔点名放行〕红例清单见上", ["501_某用例"], False),  # 段外提及不算
        ("〔点名放行〕红例 502_某用例", ["501_某用例"], False),               # 红例名缺=拒
        ("〔点名放行〕红例 501_某用例", [], False),                          # 空清单=拒
        (None, ["501_某用例"], False),                                       # 不可读=拒（miss 不静默）
        ("", ["501_某用例"], False),                                         # 空信息=拒
    ]
    for 信息, 红例们, 期望过 in 断言们:
        拒因 = 点名放行披露检查(信息, 红例们)
        实际过 = 拒因 is None
        assert 实际过 == 期望过, f"披露检查失败：{信息!r}+{红例们!r} → {拒因!r}（期望过={期望过}）"
    print(f"integrate_disclosure 自测：{len(断言们)} 例全过")
