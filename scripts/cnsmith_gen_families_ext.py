def 族程序扩(族名, seed, 族序):
    """扩面族完整程序生成（确定性：族内 rng=seed*1009+族序·与 families 同构）。

    返回源码带 `// 族=<名>` 标记（selftest 覆盖断言消费）。每族两变体，
    全部为宿主可编译的合法程序；值取小域确定形态。"""
    rng = random.Random(seed * 1009 + 族序)
    # -----------------------------------------------------------------
    # 格式化占位符族（新·素材 pA1/pA2/pA3）：宽位占位符 + 嵌套格式化 +
    #   四消费位（打印/赋值/循环/默认参数）+ 泄漏轴差值断言（块内串产出
    #   全释放→差值恒 0；非零=泄漏显形为对拍分歧）。
    # -----------------------------------------------------------------
    if 族名 == "格式化占位符":
        # 变体一：宽位基本值（%d64/%u64/%d128）+打印位+赋值位+默认参数位
        #   +循环位——组行 默认参数体内格式化=默认参数位覆盖。
        if rng.random() < 0.5:
            return r'''// 族=格式化占位符
函数 组行(整64 v, 整32 n = 3) -> 字符串 {
    返回 格式化("[%d64][%d]", v, n);
}
函数 主() -> 整32 {
    整64 基 = 内存::活动分配数();
    {
        整64 a = 4294967297;
        正64 b = 18446744073709551615;
        整128 c = -170141183460469231731687303715884105728;
        打印(格式化("a=%d64 b=%u64", a, b));
        打印(格式化("c=%d128", c));
        字符串 行 = 组行(a);
        打印(行);
        打印(字符串长度(行));
        整32 i = 0;
        整64 总 = 0;
        当 (i < 50) {
            整64 v = i;
            v = v * 1000003L + a;
            字符串 s = 格式化("%d64", v);
            总 = 总 + 字符串长度(s);
            i = i + 1;
        }
        打印(总);
    }
    打印(内存::活动分配数() - 基);
    返回 0;
}
'''
        # 变体二：嵌套格式化（格式化结果再作 %s 实参=临时串拥有性面·pA2）
        #   +%d/%s/%d64 混排循环释放+拼接隐式转换尾串。
        return r'''// 族=格式化占位符
函数 主() -> 整32 {
    整64 基 = 内存::活动分配数();
    {
        整64 a = 1234567890123L;
        打印(格式化("外%s外", 格式化("<%d64>", a)));
        打印(格式化("直%s直", 格式化("[%d]", 7)));
        整64 总 = 0;
        整32 i = 0;
        当 (i < 100) {
            整64 v = i;
            v = v * 1000000L;
            字符串 甲 = 格式化("%d-%s-%d64", i, "槽", v);
            总 = 总 + 字符串长度(甲);
            i = i + 2;
        }
        打印(总);
        字符串 拼尾 = "终" + 格式化("%d", 42);
        打印(拼尾);
    }
    打印(内存::活动分配数() - 基);
    返回 0;
}
'''
    # -----------------------------------------------------------------
    # 联合体族（新·素材 pC1/pC5/pC8）：字段访问一律 不安全 函数（执法面）。
    #   小端拆读/元素步长/结构体内联合体字段——输出值=字节布局确定形态，
    #   双侧一致即绿（值错由对拍轨道显形）。
    # -----------------------------------------------------------------
    if 族名 == "联合体":
        # 变体一：联合体含数组字段与整64 共享——小端拆读/拼写（pC1 原形态）。
        if rng.random() < 0.5:
            return r'''// 族=联合体
联合体 位块 {
    整32[2] 对;
    整64 全;
}
不安全 函数 主() -> 整32 {
    位块 块;
    块.全 = 4294967297;
    打印(块.对[0]);
    打印(块.对[1]);
    块.对[0] = 5;
    块.对[1] = 0;
    打印(块.全);
    返回 0;
}
'''
        # 变体二：联合体数组元素逐写（元素步长=最大字段对齐 8·pC5）+结构体
        #   数组元素内联合体字段写后读（pC8 同域）。
        return r'''// 族=联合体
联合体 值 {
    整32 窄;
    整64 宽;
}
结构体 槽 {
    整32 标签;
    值 u;
}
不安全 函数 主() -> 整32 {
    值[3] 组;
    组[0].宽 = 1;
    组[1].宽 = 4294967296;
    组[2].宽 = 0;
    组[2].窄 = 7;
    打印(组[0].窄);
    打印(组[1].窄);
    打印(组[2].窄);
    打印(组[2].宽);
    槽[2] 表;
    表[0].标签 = 1;
    表[0].u.宽 = 0;
    表[0].u.窄 = 7;
    打印(表[0].标签);
    打印(表[0].u.窄);
    返回 0;
}
'''
    # -----------------------------------------------------------------
    # 泛型继承接口族（新·素材 pD1/pD2/pD6）：接口方法签名收分号（执法面）；
    #   泛型类双实例（T=整32/整64）覆盖泛型实例化轴。
    # -----------------------------------------------------------------
    if 族名 == "泛型继承接口":
        # 变体一：继承非泛型基类+虚拟/重写+基类指针分派（pD2 原形态）。
        if rng.random() < 0.5:
            return r'''// 族=泛型继承接口
类 基 {
公开:
    虚拟 函数 名字() -> 字符串 { 返回 "基"; }
}
泛型 <类型 T>
类 容器 : 基 {
公开:
    T 载;
    函数 容器(T 初) { 载 = 初; }
    重写 函数 名字() -> 字符串 { 返回 "容器"; }
}
函数 主() -> 整32 {
    容器<整32> 实 = 容器<整32>(3);
    基* p = 实;
    打印(p.名字());
    打印(实.名字());
    返回 0;
}
'''
        # 变体二：实现两接口+直接调用（pD6 绿形态·双接口实现位）+泛型第二
        #   实例 T=整64（泛型实例化轴扩面）+非泛型类接口变量值形态多态
        #   （pD1a 绿形态）。
        #   ⚠ 入面否决：泛型类实例→接口的隐式转换（值/指针两形态）=宿主
        #   拒而 v2 放行的已知在案分叉（1102 轮 pD1/pD1b 双 HIT·#1982 收口
        #   归档）——不入随机合法面（「只生成合法程序」契约），拒绝域转对拍
        #   内置双侧拒绝锁 inner_泛型类接口值转换（cnsmith_dual_samples）
        #   每轮必测显形。
        return r'''// 族=泛型继承接口
接口 可取值 {
    虚拟 函数 取值() -> 整32;
}
接口 可显示 {
    虚拟 函数 显示() -> 字符串;
}
泛型 <类型 T>
类 盒子 : 可取值, 可显示 {
公开:
    T 值;
    函数 盒子(T 初) { 值 = 初; }
    重写 函数 取值() -> 整32 { 返回 1; }
    重写 函数 显示() -> 字符串 { 返回 "盒"; }
}
类 件 : 可取值 {
公开:
    整32 n;
    函数 件(整32 初) { n = 初; }
    重写 函数 取值() -> 整32 { 返回 6; }
}
函数 主() -> 整32 {
    盒子<整32> 甲 = 盒子<整32>(7);
    打印(甲.取值());
    打印(甲.显示());
    打印(甲.值);
    盒子<整64> 乙 = 盒子<整64>(1234567890123L);
    打印(乙.取值());
    打印(乙.显示());
    打印(乙.值);
    件 单 = 件(9);
    可取值 非 = 单;
    打印(非.取值());
    返回 0;
}
'''
    # -----------------------------------------------------------------
    # 堆指针链族（新·素材 pF1/pF2）：分配/类型大小/链式指针字段/无 判空/
    #   释放/递归遍历——分配配对释放（合法性契约=零泄漏·不用内存差值断言，
    #   堆面数值归运行实现细节，输出只锚遍历结果）。
