def 枚举用例() -> list:
    """E2E 用例目录（编号前缀·runner 同口径）。"""
    用例们 = []
    for 子 in sorted(E2E目录.iterdir()):
        if 子.is_dir() and re.match(r"^\d+_", 子.name):
            用例们.append(子)
    return 用例们


def main() -> int:
    用例们 = 枚举用例()
    未覆盖 = []
    有通道数 = 0
    for 用例 in 用例们:
        if any((用例 / 通道).exists() for 通道 in v2通道文件):
            有通道数 += 1
        elif 用例.name not in 豁免清单:
            未覆盖.append(用例.name)

    提示 = []
    for 名 in sorted(豁免清单):
        目录 = E2E目录 / 名
        if not 目录.is_dir():
            提示.append(f"豁免行目录不存在（清单陈旧·删除该行）: {名}")
        elif any((目录 / 通道).exists() for 通道 in v2通道文件):
            提示.append(f"豁免行用例已含 v2 通道（修复后该清理清单）：{名}")

    print("E2E v2 覆盖通道守卫（930·check_dual_coverage）")
    print(f"  用例总数: {len(用例们)}  已配 v2 通道: {有通道数}  "
          f"豁免: {len(豁免清单)}  未覆盖: {len(未覆盖)}")
    for 名 in 未覆盖:
        print(f"  [未配 v2 通道] {名}：补 双编译对照.txt（宿主+v2 双测）"
              f"或在 check_dual_coverage.py 豁免清单登记案号+理由")
    for 行 in 提示:
        print(f"  [黄] {行}")
    if len(豁免清单) > 豁免上限:
        print(f"  [红] 豁免清单 {len(豁免清单)} 行 > 上限 {豁免上限}（只减不增棘轮）"
              f"——确认新增确无替代后显式上调 豁免上限 常量并留痕")
        return 1
    if 未覆盖:
        return 1
    print("  通过：全部用例已有 v2 侧覆盖通道或豁免登记")
    return 0


if __name__ == "__main__":
    sys.exit(main())
