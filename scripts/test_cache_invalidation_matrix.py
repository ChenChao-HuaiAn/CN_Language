def fnv1a64(数据: bytes) -> int:
    值 = FNV_基准
    for 字节 in 数据:
        值 ^= 字节
        值 = (值 * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return 值


# ==================== 缓存条目头/长度/FNV 机械校验 ====================

def 校验条目完整(路径: Path, 魔数: bytes, 头长: int):
    """通用条目校验：返回 None=完整；否则缺陷说明（魔数/长度/FNV 三层）。"""
    数据 = 路径.read_bytes()
    if len(数据) < 头长:
        return "文件长度 %d < 头部 %d" % (len(数据), 头长)
    if 数据[:len(魔数)] != 魔数:
        return "魔数不符: %r" % 数据[:len(魔数)]
    载荷长 = int.from_bytes(数据[头长 - 4:头长], "little")
    if 载荷长 != len(数据) - 头长:
        return "载荷长度不符（头=%d 实际=%d）" % (载荷长, len(数据) - 头长)
    存储校验和 = int.from_bytes(数据[40:48], "little")
    实际校验和 = fnv1a64(数据[头长:])
    if 存储校验和 != 实际校验和:
        return "FNV 校验和不符（头=%016x 实际=%016x）" % (存储校验和, 实际校验和)
    return None


def 校验AST条目(路径: Path):
    return 校验条目完整(路径, AST_魔数, AST_条目头长)


def 程序载荷(数据: bytes):
    """解析程序缓存载荷：返回 (汇编字节, human 警告, json 警告)；结构不符抛异常。"""
    if len(数据) < 程序_条目头长 + 程序_载荷头长:
        raise ValueError("程序条目长度不足")
    起 = 程序_条目头长
    汇编长 = int.from_bytes(数据[起:起 + 4], "little")
    human长 = int.from_bytes(数据[起 + 4:起 + 8], "little")
    json长 = int.from_bytes(数据[起 + 8:起 + 12], "little")
    身 = 起 + 程序_载荷头长
    if 身 + 汇编长 + human长 + json长 != len(数据):
        raise ValueError("程序载荷分片长度不符")
    return (数据[身:身 + 汇编长],
            数据[身 + 汇编长:身 + 汇编长 + human长],
            数据[身 + 汇编长 + human长:])


def 校验程序条目(路径: Path):
    def 缺陷():
        return 校验条目完整(路径, 程序_魔数, 程序_条目头长)
    基础 = 缺陷()
    if 基础 is not None:
        return 基础
    try:
        程序载荷(路径.read_bytes())
    except ValueError as 错:
        return str(错)
    return None


def 快照(目录: Path, 后缀: str):
    return {p.name: p.read_bytes() for p in sorted(目录.glob("*" + 后缀))}


