def 旁路环境(AST目录: Path, 程序目录: Path, 额外=None):
    """干净缓存环境：清空全部缓存相关变量（含继承的 VERIFY/NO_CACHE/STATS/DIR）。"""
    环境 = dict(os.environ)
    for 键 in ("CN_AST_CACHE_VERIFY", "CN_NO_AST_CACHE", "CN_AST_CACHE_STATS",
               "CN_AST_CACHE_DIR", "CN_PROGRAM_CACHE_VERIFY", "CN_NO_PROGRAM_CACHE",
               "CN_PROGRAM_CACHE_STATS", "CN_PROGRAM_CACHE_DIR"):
        环境.pop(键, None)
    环境["CN_AST_CACHE_DIR"] = str(AST目录)
    环境["CN_AST_CACHE_STATS"] = "1"
    环境["CN_PROGRAM_CACHE_DIR"] = str(程序目录)
    环境["CN_PROGRAM_CACHE_STATS"] = "1"
    if 额外:
        环境.update(额外)
    return 环境


def 解析统计(文本: str, 模式, 字段名):
    匹配 = 模式.findall(文本)
    assert 匹配, "编译输出缺统计行（CN_*_CACHE_STATS=1 生效？）\n" + 文本[-800:]
    return dict(zip(字段名, (int(v) for v in 匹配[-1])))


def 解析可选统计(文本: str, 模式, 字段名):
    """失败编译可能在任何阶段提前返回（缓存统计收尾未执行）：无统计行=返回 None。"""
    匹配 = 模式.findall(文本)
    if not 匹配:
        return None
    return dict(zip(字段名, (int(v) for v in 匹配[-1])))


def 编译(编译器: Path, 工作目录: Path, 源文件: Path, 输出: Path,
         选项列表, AST目录: Path, 程序目录: Path, 额外环境=None,
         期望成功=True) -> 编译结果:
    命令 = [str(编译器), "compile", str(源文件), "--output", str(输出)] + list(选项列表)
    结果 = subprocess.run(命令, cwd=str(工作目录), capture_output=True, timeout=180,
                          env=旁路环境(AST目录, 程序目录, 额外环境))
    文本 = (结果.stdout + 结果.stderr).decode("utf-8", errors="replace")
    if 期望成功:
        assert 结果.returncode == 0, "编译失败（rc=%d）：%s" % (结果.returncode, 文本[-800:])
    else:
        assert 结果.returncode != 0, "预期编译失败但 rc=0：%s" % 文本[-800:]
    return 编译结果(结果.returncode, 结果.stdout, 结果.stderr,
                    解析可选统计(文本, AST_统计模式, AST_字段),
                    解析可选统计(文本, 程序_统计模式, 程序_字段), 文本)


def 无缓存编译(编译器: Path, 工作目录: Path, 源文件: Path, 输出: Path,
              选项列表, AST目录: Path, 程序目录: Path) -> bytes:
    """两级缓存全关的完整编译产物（一切一致性对照的基准）。"""
    结果 = 编译(编译器, 工作目录, 源文件, 输出, 选项列表, AST目录, 程序目录,
                {"CN_NO_AST_CACHE": "1", "CN_NO_PROGRAM_CACHE": "1"})
    断言(结果.AST统计["命中"] == 0 and 结果.AST统计["首建"] == 0,
         "无缓存对照未走 AST 缓存（CN_NO_AST_CACHE=1）")
    断言(结果.程序统计["命中"] == 0 and 结果.程序统计["首建"] == 0,
         "无缓存对照未走程序缓存（CN_NO_PROGRAM_CACHE=1）")
    return 输出.read_bytes()


def 建项目(目录: Path):
    """双模块项目：入口（宏条件编译 + 调用依赖）与依赖（常量返回值）。"""
    目录.mkdir(parents=True, exist_ok=True)
    主 = 目录 / "主.cn"
    工具 = 目录 / "工具.cn"
    写主源(主, "乙分支")
    写工具源(工具, 42)
    return 主, 工具


