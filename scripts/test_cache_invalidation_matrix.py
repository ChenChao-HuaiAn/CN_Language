def 场景0_双路径验证(编译器, 工作目录, 缓存根):
    print("[场景①] 双路径一致性：AST/程序缓存 VERIFY 命中后完整重编译逐字节比对")
    AST目录, 程序目录 = 缓存根 / "ast", 缓存根 / "prog"
    主, _ = 建项目(工作目录 / "verify")
    选项 = ["--target", 本机目标平台(), "-O2"]
    基准文件 = 工作目录 / "verify" / "基准.asm"
    首次 = 编译(编译器, 主.parent, 主, 基准文件, 选项, AST目录, 程序目录)
    统计断言(首次, "AST", {"命中": 0, "首建": 2, "失效重建": 0}, "首次编译：两模块 AST 首建")
    统计断言(首次, "程序", {"命中": 0, "首建": 1}, "首次编译：程序产物首建")
    基准 = 基准文件.read_bytes()

    验证文件 = 工作目录 / "verify" / "验证.asm"
    验证 = 编译(编译器, 主.parent, 主, 验证文件, 选项, AST目录, 程序目录,
                {"CN_AST_CACHE_VERIFY": "1", "CN_PROGRAM_CACHE_VERIFY": "1"})
    统计断言(验证, "AST", {"命中": 2, "首建": 0, "损坏回退": 0},
             "双验证命中：AST 两级模块均命中且无漂移（无损坏回退）")
    统计断言(验证, "程序", {"命中": 1, "验证不符": 0},
             "双验证命中：程序缓存命中且验证不符=0")
    断言("[程序缓存验证] 通过：命中产物与重编译产物逐字节一致" in 验证.文本,
         "程序缓存验证通道显式报告逐字节一致")
    断言("错误: [AST 缓存验证]" not in 验证.文本,
         "AST 验证通道无漂移错误（命中 AST 与重新解析一致）")
    断言(验证文件.read_bytes() == 基准, "双验证命中产物与首次完整编译逐字节一致")

    # 程序缓存漂移注入：改汇编分片一字节并重算 FNV（结构/长度/校验和全部合法，
    # 仅内容错误）——验证通道必须抓到「命中但过期」而不是盲目复用。
    程序条目 = sorted(程序目录.glob("*.cnpg"))
    断言(len(程序条目) == 1, "程序缓存单条目（实际 %d）" % len(程序条目))
    数据 = bytearray(程序条目[0].read_bytes())
    汇编长 = int.from_bytes(数据[52:56], "little")
    assert 汇编长 > 0, "程序缓存汇编分片为空"
    数据[68] ^= 0xFF  # 汇编首字节翻转（68=头 52 + 载荷头 16）
    数据[40:48] = fnv1a64(bytes(数据[52:])).to_bytes(8, "little")
    程序条目[0].write_bytes(bytes(数据))
    断言(校验程序条目(程序条目[0]) is None, "漂移注入后程序条目头/长度/FNV 仍合法")
    漂移 = 编译(编译器, 主.parent, 主, 工作目录 / "verify" / "漂移.asm", 选项,
                AST目录, 程序目录,
                {"CN_AST_CACHE_VERIFY": "1", "CN_PROGRAM_CACHE_VERIFY": "1"})
    断言("错误: [程序缓存验证] 命中产物与重编译产物不一致" in 漂移.文本,
         "程序缓存验证抓到手改产物漂移（命中但过期=显形）")
