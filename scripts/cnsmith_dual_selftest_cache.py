def _自测缓存轴(签):
    """#1556 缓存对拍轴：统计行解析/缓存行剥离/双跑判定闭集正反例/建议立案标题。"""
    统计行 = ("[AST 缓存] 命中=3 首建=1 失效重建=0 损坏回退=0 "
              "写入=1 写失败=0 序列化失败=0")
    统计 = 缓存轴.解析缓存统计行("前置输出\n" + 统计行 + "\n后续")
    签("缓存轴：统计行解析七字段（真实 driver 格式逐字）",
       统计 == {"命中": 3, "首建": 1, "失效重建": 0, "损坏回退": 0,
                "写入": 1, "写失败": 0, "序列化失败": 0}, str(统计))
    签("缓存轴：统计行缺失 → None（显式哨兵·调用方跳过不当绿）",
       缓存轴.解析缓存统计行("普通警告行\n无统计") is None
       and 缓存轴.解析缓存统计行("") is None)
    验证行全文 = ("错误: [AST 缓存验证] 反序列化 AST 与重新解析不一致"
                  "（回退解析结果）: x.cn")
    剩, 行们 = 缓存轴.剥离缓存行(
        "普通行\n" + 统计行 + "\n" + 验证行全文 + "\n尾行")
    签("缓存轴：剥离缓存行——统计/验证行出比对面且全量捕获（证据不丢）",
       剩 == "普通行\n尾行" and len(行们) == 2
       and 缓存轴.验证错误行们(行们) == [验证行全文],
       repr(剩) + str(行们))

    def 跑(命中, 损坏=0, rc=0, stdout="甲\n乙\n", 编译rc=0, stderr=""):
        return {"编译rc": 编译rc,
                "编译stderr": "编译提示\n[AST 缓存] 命中=%d 首建=1 失效重建=0 "
                              "损坏回退=%d 写入=1 写失败=0 序列化失败=0\n" % (命中, 损坏),
                "rc": rc, "stdout": stdout, "stderr": stderr}

    def 判(甲, 乙, 验证行=(), stderr甲="", stderr乙="", 比stderr=False):
        统计甲 = 缓存轴.解析缓存统计行(甲["编译stderr"])
        统计乙 = 缓存轴.解析缓存统计行(乙["编译stderr"])
        return 缓存轴.缓存双跑判定(甲, 乙, 统计甲, 统计乙, list(验证行),
                                stderr甲, stderr乙, 比stderr)

    判定, 原因, 详情, 首 = 判(跑(0), 跑(3))
    签("缓存轴判定正例：命中跑命中≥1+损坏=0+rc/stdout 同 → 一致",
       判定 == 报告.判定_一致 and 原因 == 报告.原因_一致 and 首 is None
       and "命中=3" in 详情, "%s %s" % (判定, 详情))
    判定, 原因, 详情, 首 = 判(跑(0), 跑(0))
    签("缓存轴反例：命中跑命中=0 → 缓存分叉（原因=缓存二次未命中）",
       判定 == 报告.判定_缓存分叉 and 原因 == 报告.原因_缓存命中缺失
       and 首 and 首["乙"] == "命中=0", "%s %s" % (判定, 详情))
    判定, 原因, 详情, _ = 判(跑(0), 跑(3, 损坏=2))
    签("缓存轴反例：命中跑损坏回退=2 → 缓存分叉（原因=损坏回退非零）",
       判定 == 报告.判定_缓存分叉 and 原因 == 报告.原因_缓存损坏回退
       and "损坏回退=2" in 详情, "%s %s" % (判定, 详情))
    判定, 原因, _, _ = 判(跑(0), 跑(0), 验证行=[验证行全文])
    签("缓存轴反例：验证错误行优先显形（原因=缓存验证错误行）",
       判定 == 报告.判定_缓存分叉 and 原因 == 报告.原因_缓存验证失败,
       "%s %s" % (判定, 原因))
    判定, 原因, _, _ = 判(跑(0), 跑(3, 编译rc=1))
    签("缓存轴反例：缓存环境编译失败 → 缓存分叉（原因=缓存环境编译失败）",
       判定 == 报告.判定_缓存分叉 and 原因 == 报告.原因_缓存编译失败,
       "%s %s" % (判定, 原因))
    判定, 原因, _, 首 = 判(跑(0, rc=0), 跑(3, rc=3))
    签("缓存轴反例：rc 不一致 → 缓存分叉（首差异类别=rc·甲乙侧=首跑/命中跑）",
       判定 == 报告.判定_缓存分叉 and 原因 == 报告.原因_缓存输出不一致
       and 首 and 首["类别"] == "rc" and 首["甲侧"] == "宿主首跑"
       and 首["乙侧"] == "宿主命中跑", "%s %s" % (判定, 首))
    判定, 原因, _, 首 = 判(跑(0), 跑(3, stdout="甲\nX\n"))
    签("缓存轴反例：stdout 篡改 → 缓存分叉（首差异行=2）",
       判定 == 报告.判定_缓存分叉 and 首 and 首["行"] == 2
       and 首["类别"] == "stdout", "%s %s" % (判定, 首))
    判定, 原因, 详情, _ = 判(跑(0), 跑(3), stderr甲="运行甲\n", stderr乙="运行乙\n",
                          比stderr=True)
    签("缓存轴反例：stderr 分叉（比stderr·剥离缓存行后仍检出）",
       判定 == 报告.判定_缓存分叉 and 原因 == 报告.原因_缓存输出不一致,
       "%s %s" % (判定, 原因))
    空跑 = {"编译rc": 0, "编译stderr": "无统计行", "rc": 0, "stdout": "", "stderr": ""}
    判定, 原因, 详情, _ = 判(跑(0), 空跑)
    签("缓存轴反例：统计行解析失败 → 显式跳过不当绿（原因=缓存统计行缺失）",
       判定 == 报告.判定_跳过 and 原因 == 报告.原因_缓存统计缺失
       and "跳过" in 详情, "%s %s" % (判定, 详情))
    记录 = {"判定": 报告.判定_缓存分叉, "原因": 报告.原因_缓存命中缺失,
            "样本": "s1#缓存", "来源": "自测",
            "首差异": {"行": 0, "类别": "缓存命中", "甲侧": "宿主首跑",
                      "乙侧": "宿主命中跑", "甲": "首建=1", "乙": "命中=0"}}
    标题 = 缓存轴.缓存建议立案标题(记录)
    签("缓存轴：建议立案标题含轴标注/样本名/首跑×命中跑措辞",
       "缓存轴" in 标题 and "s1#缓存" in 标题 and "首跑×命中跑" in 标题, 标题)
    签("缓存轴：一致/跳过不给建议立案标题",
       缓存轴.缓存建议立案标题({"判定": 报告.判定_一致}) == ""
       and 缓存轴.缓存建议立案标题({"判定": 报告.判定_跳过}) == "")


def _自测缓存轴汇总(签):
    """#1556 缓存轴汇总面：命中归档独立桶「缓存/」+ 轨道速记/摘要行缓存段。"""
    临时 = 根 / "target" / "cnsmith_dual_selftest_cache"
    if 临时.exists():
        shutil.rmtree(临时)
    临时.mkdir(parents=True)
    try:
        源 = 临时 / "s1.cn"
        源.write_text("函数 主() -> 整32 { 返回 0; }\n", encoding="utf-8")
        命中记录 = {"样本": "s1#缓存", "源": str(源), "整树": False, "缓存轴": True,
                    "判定": 报告.判定_缓存分叉, "原因": 报告.原因_缓存命中缺失,
                    "详情": "命中跑 命中=0",
                    "缓存统计": {"首跑": {"命中": 0, "首建": 1},
                                "命中跑": {"命中": 0, "首建": 0}},
                    "缓存验证行们": []}

        class _参:
            入命中库 = False

        落 = cnsmith_run.归档本轮命中(
            _参(), 临时, "自测轮-缓存轴", {"编译器": {"仓库HEAD": "x" * 40}},
            {"对拍": {"状态": "完成", "清单": [命中记录]}})
        相对 = (落[0].replace("\\", "/") if 落 else "")
        元文本 = 核心.读文本(临时 / "命中" / "缓存" / "自测轮_s1.cn.meta")
        签("缓存轴归档：命中样本落独立桶 命中/缓存/（与 dual/ 分开）",
           len(落) == 1 and 相对.endswith("命中/缓存/自测轮_s1.cn"), 相对)
        签("缓存轴归档：meta 带轴标注/首跑命中跑统计/判定",
           "轴: 缓存对拍" in 元文本 and "统计: " in 元文本
           and "命中跑=" in 元文本 and "判定: 缓存分叉" in 元文本, 元文本[:200])
    finally:
        shutil.rmtree(临时, ignore_errors=True)
    缓结果 = {"状态": "完成", "一致": 5, "样本数": 5, "跳过数": 0,
             "缓存对拍": {"启用": True, "样本数": 3, "一致": 3,
                        "命中": 0, "统计缺失": 0}}
    速 = cnsmith_run.轨道速记("对拍", 缓结果)
    签("缓存轴速记：启用时 缓存对拍=一致/样本数 段（摘要行数据源）",
       速.startswith("对拍=5/5") and "缓存对拍=3/3" in 速, 速)
    分叉速 = cnsmith_run.轨道速记("对拍", dict(缓结果, 缓存对拍=dict(
        缓结果["缓存对拍"], 一致=2, 命中=1)))
    签("缓存轴速记：分叉数附注（缓存对拍=2/3(分叉1)）",
       "缓存对拍=2/3(分叉1)" in 分叉速, 分叉速)
    关速 = cnsmith_run.轨道速记("对拍", {"状态": "完成", "一致": 2, "样本数": 2,
                                    "跳过数": 0,
                                    "缓存对拍": {"启用": False, "说明": "缓存对拍=关"}})
    签("缓存轴速记：显式关时标 缓存对拍=关（不冒充启用）",
       "缓存对拍=关" in 关速, 关速)
    旧速 = cnsmith_run.轨道速记("对拍", {"状态": "完成", "一致": 4, "样本数": 4,
                                    "跳过数": 0})
    签("缓存轴速记：无缓存键的旧结构不追加缓存段（向后兼容）",
       旧速 == "对拍=4/4" and "缓存" not in 旧速, 旧速)
