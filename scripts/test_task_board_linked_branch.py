"""2097：task_board.在飞承载号 最小正反自测（#1011 检查工具改动须 selftest）。

背景：cmd_check 对 🏃 在飞任务的分支存在性判定原按 任务/<号> 拼名硬查——
联动件形态（一分支多任务·台账行分支字段显式登记承载分支，如 2090 与 2089
同分支）恒误红挡全局集成队列（#2090 实锚 2026-11-06）。根修=在飞承载号()
优先取分支字段登记号，分支字段空回退任务号（主形态不变）。

正反四例：
  正1 联动件（分支字段=任务/2089·远端含 2089）→ 判定号 2089 → 不误红
  正2 主形态（分支字段空）→ 判定号=任务号（行为不变）
  反1 联动件但承载分支也不在远端 → 判定号=2089 → 仍红（不因联动豁免漏红）
  反2 batch/ 前缀分支字段同样识别（组链批分支字段形态）
退出码 0=全过；非 0=有失败（打印差异）。
"""
import sys
import pathlib

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from task_board import 在飞承载号  # noqa: E402


def 主():
    用例们 = [
        # (描述, 台账行, 期望判定号)
        ("联动件分支字段=任务/2089 → 取 2089",
         {"号": "2090", "分支": "任务/2089"}, "2089"),
        ("主形态分支字段空 → 取任务号",
         {"号": "2097", "分支": ""}, "2097"),
        ("组链批前缀 batch/2097 → 取 2097",
         {"号": "2097", "分支": "batch/2097"}, "2097"),
        ("分支字段带空白 → 容错取号",
         {"号": "2090", "分支": " 任务/2089 "}, "2089"),
    ]
    失败 = []
    for 描述, 行, 期望 in 用例们:
        实际 = 在飞承载号(行)
        if 实际 != 期望:
            失败.append(f"{描述}：期望 {期望} 实际 {实际}")
    for 描述, 行, 期望 in 用例们:
        print(f"[{'PASS' if 在飞承载号(行) == 期望 else 'FAIL'}] {描述}")
    if 失败:
        print("\n".join(失败))
        return 1
    print("[OK] 在飞承载号 四例全过（联动件不误红·真死账仍红·主形态不变）")
    return 0


if __name__ == "__main__":
    sys.exit(主())
