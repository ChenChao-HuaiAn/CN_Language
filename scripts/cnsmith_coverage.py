# ============ 样本预处理（剥注释/字符串内容·保留形态骨架）============

def 剥壳(文本: str) -> str:
    """CN 源文本剥壳：注释移除、字符串/字符内容占位（保留 "~" / '~' 骨架）。

    单遍扫描（非正则——正则难处理转义与嵌套）；未闭合引号按行尾收尾（容错）。"""
    出 = []
    i, n = 0, len(文本)
    while i < n:
        c = 文本[i]
        nxt = 文本[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = 文本.find("\n", i)
            i = n if j < 0 else j
        elif c == "/" and nxt == "*":
            j = 文本.find("*/", i + 2)
            i = n if j < 0 else j + 2
            出.append(" ")
        elif c in ("\"", "'"):
            闭 = c
            j = i + 1
            while j < n:
                if 文本[j] == "\\":
                    j += 2
                    continue
                if 文本[j] == 闭 or 文本[j] == "\n":
                    break
                j += 1
            出.append("\"~\"" if c == "\"" else "'~'")
            i = j + 1
        else:
            出.append(c)
            i += 1
    return "".join(出)


