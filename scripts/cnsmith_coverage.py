def 检测_函数调用(剥壳文本: str, 原文: str) -> bool:
    """函数/方法调用：剥控制关键字括号（如果/当/选择/循环）后的 `名(`。"""
    净 = re.sub(r"(?:如果|当|选择|循环|遍历|返回|类型大小|转移|打印行|打印到错误|打印)"
              r"\s*[\(（]", " ", 剥壳文本)
    return re.search(r"[\w\u4e00-\u9fff]+\s*\(", 净) is not None


def 检测_引用参数(剥壳文本: str, 原文: str) -> bool:
    """引用参数/引用类型：函数签名参数段含 &（`类型& 名`）。"""
    for m in re.finditer(r"(?:函数|方法)?\s*\w+\s*\(([^()]*)\)", 剥壳文本):
        参数段 = m.group(1)
        if re.search(r"[\w\u4e00-\u9fff]+\s*&\s*[\w\u4e00-\u9fff]", 参数段):
            return True
    return False


def 检测_函数重载(剥壳文本: str, 原文: str) -> bool:
    名们 = re.findall(r"(?<!\w)函数\s+([\w\u4e00-\u9fff]+)\s*\(", 剥壳文本)
    return any(名们.count(名) >= 2 for 名 in set(名们))


def 检测_默认参数(剥壳文本: str, 原文: str) -> bool:
    for m in re.finditer(r"(?<!\w)函数\s+\w+\s*\(([^()]*)\)", 剥壳文本):
        if re.search(r"[\w\u4e00-\u9fff]+\s*=\s*[^,)]+", m.group(1)):
            return True
    return False


def 检测_嵌套块(剥壳文本: str, 原文: str) -> bool:
    深度 = 最大 = 0
    for c in 剥壳文本:
        if c == "{":
            深度 += 1
            最大 = max(最大, 深度)
        elif c == "}":
            深度 = max(0, 深度 - 1)
    return 最大 >= 3      # 函数体=1、语句块内=2、再嵌套=3（含函数体算「嵌套块」）


