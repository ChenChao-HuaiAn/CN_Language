# ============ 差分归因（按语法形态维度分组）============

清单行正则 = re.compile(r"(\S+\.cn)\s*\[(\w+)\]:\s*(.*)")


def 解析分歧清单(清单路径: pathlib.Path) -> list:
    """解析 cnsmith_diff 分歧清单（与 cnsmith_daemon.差分 的清单解析同构——
    第 2 处重复已留标记·第 3 处出现前提炼为公共函数）。"""
    分歧 = []
    for 行 in 清单路径.read_text(encoding="utf-8", errors="replace").splitlines():
        m = 清单行正则.match(行.strip())
        if m:
            分歧.append((m.group(1), m.group(2), m.group(3)))
    return 分歧


def 归因差分(清单路径: pathlib.Path, 样本目录: pathlib.Path) -> dict:
    """读分歧清单 × 样本目录 → 逐分歧样本形态检测 → 按形态分组统计。"""
    分歧 = 解析分歧清单(清单路径)
    命中 = {形态["名"]: [] for 形态 in 形态清单}
    缺样本 = []
    for 名, 类别, _详情 in 分歧:
        样本文件 = 样本目录 / 名
        if not 样本文件.exists():
            缺样本.append(名)
            continue
        源码 = 样本文件.read_text(encoding="utf-8", errors="replace")
        壳 = 剥壳(源码)
        for 形态 in 形态清单:
            if 形态["检"](壳, 源码):
                命中[形态["名"]].append(名)
    return {"分歧": 分歧, "命中": 命中, "缺样本": 缺样本}


def 打印归因报告(清单路径: pathlib.Path, 样本目录: pathlib.Path, 归因: dict,
               归因输出: str) -> int:
    分歧, 命中, 缺样本 = 归因["分歧"], 归因["命中"], 归因["缺样本"]
