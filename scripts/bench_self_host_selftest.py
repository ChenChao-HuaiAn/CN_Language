#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""bench_self_host_selftest.py —— 自举基线脚本内置自测（#1333）。

纯本机零编译器、秒级：参数解析边界（样本数 clamp/缓存口径/仅M1M2）、
样本极差、报告视图五分支、报告正文口径字段、失败说明节、产物防假绿
（缺失/无入口/行数不足/正常）、M6 固定点（同/异/缺失）、输入规模非空。
正反两态均断言——自测自身退化（全部空转）会立即红。
"""
from __future__ import annotations

import contextlib
import io
import pathlib
import tempfile

import bench_self_host as 主


def _断言器():
    失败: list[str] = []

    def 断言(名: str, 条件: bool, 详情: str = "") -> None:
        if 条件:
            print(f"  ✓ {名}")
        else:
            失败.append(名)
            print(f"  ✗ {名} {详情}")

    return 断言, 失败


def _成功结果() -> dict:
    return {
        "M1": 100.0, "M1样本": [98.0, 100.0, 105.0],
        "M2": 400.0, "M2样本": [390.0, 400.0, 430.0],
        "M2行数": 120000, "M2错误": "",
        "M3": 10.0, "M4": 20.0,
        "M5": 405.0, "M5样本": [400.0, 405.0, 410.0],
        "M5行数": 120000, "M5错误": "",
    }


def 自测() -> int:
    print("== bench_self_host 自测（#1333）==")
    断言, 失败 = _断言器()

    # 一、参数解析边界
    原 = (主.样本数, 主.M1样本数, 主.缓存口径, 主.命令超时秒)
    try:
        参数 = 主.解析参数(["--样本数", "0", "--M1样本数", "-3",
                        "--缓存", "cold", "--仅M1M2", "--报告", "x.md"])
        断言("--样本数 0 → clamp 1", 主.样本数 == 1, str(主.样本数))
        断言("--M1样本数 -3 → clamp 1", 主.M1样本数 == 1, str(主.M1样本数))
        断言("--缓存 cold 生效", 主.缓存口径 == "cold")
        断言("--仅M1M2 生效", 参数.仅M1M2 is True)
        断言("--报告 透传", 参数.报告 == "x.md")
        环境 = 主.缓存环境()
        断言("cold 注入三缓存开关",
            环境.get("CN_NO_AST_CACHE") == "1"
            and 环境.get("CN_NO_PROGRAM_CACHE") == "1"
            and 环境.get("CN_NO_V2_PROGRAM_CACHE") == "1", str(环境))
        主.解析参数(["--缓存", "asis", "--样本数", "5", "--M1样本数", "3"])
        断言("asis 不注入环境", 主.缓存环境() == {})
        断言("--样本数 5 透传", 主.样本数 == 5, str(主.样本数))
        断言("--M1样本数 3 透传", 主.M1样本数 == 3, str(主.M1样本数))
        with contextlib.redirect_stderr(io.StringIO()):
            try:
                主.解析参数(["--缓存", "bogus"])
                断言("非法缓存值 → argparse 退出", False, "未退出")
            except SystemExit:
                断言("非法缓存值 → argparse 退出", True)
    finally:
        主.样本数, 主.M1样本数, 主.缓存口径, 主.命令超时秒 = 原

    # 二、样本极差
    断言("极差：空样本=0", 主.样本极差([]) == 0.0)
    断言("极差：单样本=0", 主.样本极差([7.5]) == 0.0)
    断言("极差：多样本=最大-最小", 主.样本极差([3.0, 9.0, 5.0]) == 6.0)

    # 三、报告视图五分支（失败/跳过/成功）
    成功 = _成功结果()
    视图 = 主.报告视图(成功, True)
    断言("成功分支：固定点成立", "固定点成立" in 视图["结论"], 视图["结论"])
    断言("成功分支：M1 中位", abs(视图["m1"] - 100.0) < 1e-9)
    断言("成功分支：M1 极差=7", abs(视图["m1极差"] - 7.0) < 1e-9,
         str(视图["m1极差"]))
    断言("成功分支：M2 极差=40", abs(视图["m2极差"] - 40.0) < 1e-9,
         str(视图["m2极差"]))
    断言("成功分支：M5 极差=10", abs(视图["m5极差"] - 10.0) < 1e-9,
         str(视图["m5极差"]))
    断言("成功分支：比值 4.00x", 视图["比值vscpp显示"] == "4.00x",
         str(视图["比值vscpp显示"]))

    视图坏 = 主.报告视图({**成功, "M2错误": "超时"}, False)
    断言("M2 失败分支：仅 M1 有效", "仅 M1 有效" in 视图坏["结论"], 视图坏["结论"])
    断言("M2 失败分支：M3 未执行", "未执行" in 视图坏["m3显示"], 视图坏["m3显示"])

    视图仅 = 主.报告视图({**成功, "仅M1M2": True}, False)
    断言("仅M1M2 分支：显式标注", "--仅M1M2" in 视图仅["结论"], 视图仅["结论"])
    断言("仅M1M2 分支：M5 跳过", "跳过" in 视图仅["m5显示"], 视图仅["m5显示"])

    视图M5坏 = 主.报告视图({**成功, "M5错误": "cn_self 崩"}, False)
    断言("M5 失败分支：降级", "M5/M6 未达成" in 视图M5坏["结论"], 视图M5坏["结论"])

    视图跳 = 主.报告视图({**成功, "M5跳过": True}, False)
    断言("M5 跳过分支：标注", "--跳过M5" in 视图跳["结论"], 视图跳["结论"])

    视图不一致 = 主.报告视图(成功, False)
    断言("固定点不一致分支", "固定点不一致" in 视图不一致["结论"],
         视图不一致["结论"])

    # 四、报告正文口径字段（机器/构建类型/缓存/样本离散度/噪声带）
    文本 = "\n".join(主.报告正文行们(成功, 视图, pathlib.Path("target/cn.exe"),
                                {"主.cn": 1000, "驱动/程序缓存.cn": 500}, "win-x64"))
    断言("报告含机器", "**机器**" in 文本)
    断言("报告含构建类型", "**构建类型（宿主）**" in 文本)
    断言("报告含缓存口径", "**缓存口径**" in 文本)
    断言("报告含样本与离散度节", "样本与离散度" in 文本)
    断言("报告含中位/极差表头", "中位(ms)" in 文本 and "极差(ms)" in 文本)
    断言("报告含输入规模", "1500 行" in 文本, "1500 行 未出现")
    断言("报告含噪声带 <2% 无结论", "差异 <2% 一律无结论" in 文本)
    断言("报告含跨机不比绝对值", "跨机比较无意义" in 文本)

    # 五、失败/跳过说明节（节号统一为「四」）
    断言("M2 失败说明节号", "四、M2 失败" in "\n".join(主.失败说明行们({**成功, "M2错误": "超时"})))
    断言("仅M1M2 说明节", "四、M3~M6 跳过说明" in "\n".join(主.失败说明行们({**成功, "仅M1M2": True})))
    断言("M5 跳过说明节", "四、M5 跳过说明" in "\n".join(主.失败说明行们({**成功, "M5跳过": True})))
    断言("成功结果无失败说明", 主.失败说明行们(成功) == [])

    # 六、产物防假绿（正反两态）
    with tempfile.TemporaryDirectory() as 临时:
        目录 = pathlib.Path(临时)
        行数, 错 = 主.校验编译产物(目录 / "缺.asm", "win-x64")
        断言("产物缺失 → 红", 行数 == 0 and "未落盘" in 错, 错)
        无入口 = 目录 / "无入口.asm"
        无入口.write_text("line\n" * 100001, encoding="utf-8")
        行数, 错 = 主.校验编译产物(无入口, "win-x64")
        断言("产物无入口 → 红", 行数 == 0 and "入口符号" in 错, 错)
        过短 = 目录 / "过短.asm"
        过短.write_text("cn_main PROC\nline\n", encoding="utf-8")
        行数, 错 = 主.校验编译产物(过短, "win-x64")
        断言("产物行数不足 → 红", 行数 == 0 and "下界" in 错, 错)
        正常 = 目录 / "正常.asm"
        正常.write_text("cn_main PROC\n" + "line\n" * 100000, encoding="utf-8")
        行数, 错 = 主.校验编译产物(正常, "win-x64")
        断言("正常产物 → 绿", 错 == "" and 行数 >= 主.行数下界, f"{行数} {错}")
        正常GAS = 目录 / "正常.s"
        正常GAS.write_text(".globl cn_main\n" + "line\n" * 100000, encoding="utf-8")
        行数, 错 = 主.校验编译产物(正常GAS, "linux-x86_64")
        断言("GAS 入口标记 → 绿", 错 == "" and 行数 >= 主.行数下界, f"{行数} {错}")

    # 七、M6 固定点（同/异/缺失）
    with tempfile.TemporaryDirectory() as 临时:
        目录 = pathlib.Path(临时)
        fixp = 目录 / "fix_p.asm"
        fixs = 目录 / "fix_s.asm"
        fixp.write_text("A", encoding="utf-8")
        fixs.write_text("A", encoding="utf-8")
        断言("M6 逐字节相同 → True", 主.测量M6(fixp, fixs) is True)
        fixs.write_text("B", encoding="utf-8")
        断言("M6 不同 → False", 主.测量M6(fixp, fixs) is False)
        fixs.unlink()
        try:
            主.测量M6(fixp, fixs)
            断言("M6 缺失 → 退出", False, "未退出")
        except SystemExit:
            断言("M6 缺失 → 退出", True)

    # 八、输入规模（真实 v2 树非空——报告口径的前提）
    规模 = 主.统计输入规模()
    断言("输入规模非空", len(规模) > 0 and sum(规模.values()) > 0,
         f"{len(规模)} 文件 {sum(规模.values())} 行")

    总 = len(失败)
    print(f"\n自测结果: {'全绿' if 总 == 0 else f'{总} 项失败'}")
    return 0 if 总 == 0 else 1
