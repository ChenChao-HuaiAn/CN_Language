import os
import re
import sys

# 行首位置前缀：`<路径>:<行>:<列>:`（宿主诊断行首形态，见语义层 report 输出）
# 路径支 = 含分隔符的路径（`C:/…`、`tests/e2e/…`）或裸文件名（`主.cn`/`货舱.toml`）
位置前缀 = re.compile(
    r"^[ \t]*(?P<路径>(?:[A-Za-z]:)?[^\s:，。；、]*[/\\][^\s:，。；、]*"
    r"|[^\s:，。；、]*\.(?:cn|toml)):\d+:\d+:[ \t]*")

路径占位 = "〈路径〉"


def 路径变体(路径) -> list:
    """注入路径的全部可能回显形态（长的在前，防短形先替留下尾巴）。"""
    原形 = str(路径).strip()
    if not 原形:
        return []
    变体 = {原形, 原形.replace("\\", "/"), 原形.replace("/", "\\")}
    绝对 = os.path.abspath(原形)
    变体 |= {绝对, 绝对.replace("\\", "/"), 绝对.replace("/", "\\")}
    try:
        相对 = os.path.relpath(绝对)
        变体 |= {相对, 相对.replace("\\", "/"), 相对.replace("/", "\\")}
    except ValueError:
        pass  # 跨盘符（win）无相对形——非静默：无相对形即无该变体
    return sorted((v for v in 变体 if v), key=len, reverse=True)


def 规范化诊断(输出: str, 注入路径们=(), 用例名: str = "") -> str:
    """剥位置前缀 + 掩蔽注入路径/用例目录名——返回只含诊断正文的文本。"""
    文本 = 输出
    # ① 逐行剥行首位置前缀（任意路径·不限注入者）
    文本 = "\n".join(位置前缀.sub("", 行) for 行 in 文本.splitlines())
    # ② 掩蔽注入路径全变体（大小写不敏感：win 盘符/路径大小写回显不定）
    for 路径 in 注入路径们:
        for 变体 in 路径变体(路径):
            文本 = re.sub(re.escape(变体), 路径占位, 文本, flags=re.IGNORECASE)
    # ③ 掩蔽用例目录名整串
    if 用例名:
        文本 = 文本.replace(用例名, 路径占位)
    return 文本


def 锚命中(锚: str, 输出: str, 注入路径们=(), 用例名: str = "") -> bool:
    """负测断言判定：锚是否出现在「去掉路径回显」的诊断正文中。"""
    if not 锚:
        return True  # 空锚=只锚退出码（契约不变）
    return 锚 in 规范化诊断(输出, 注入路径们, 用例名)


